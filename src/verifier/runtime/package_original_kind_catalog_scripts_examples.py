@dataclass(frozen=True)
class _EffectScan:
    """Live scan of one owner: effect hits, unresolved imports, opaque binaries, and code."""

    hits: tuple[tuple[str, str, int, str], ...]
    opens: tuple[str, ...]
    opaque: tuple[str, ...]
    code: tuple[str, ...]


def _import_candidates(path: str, module: str, level: int) -> tuple[str, ...]:
    """Repository paths an import could bind, using the importing file's directory."""

    directory = PurePosixPath(path).parent
    if level:
        for _ in range(level - 1):
            directory = directory.parent
        parts = tuple(module.split(".")) if module else ()
        bases = (directory,)
    else:
        parts = tuple(module.split("."))
        bases = (PurePosixPath("src"), directory, PurePosixPath("."))
    stems = [PurePosixPath(base, *parts) for base in bases]
    return tuple(
        f"{stem.as_posix()}{suffix}"
        for stem in stems
        for suffix in (".py", "/__init__.py")
    )


def _inert_python(tree: ast.Module) -> bool:
    """Whether a module holds only a docstring, __future__ imports, or pass statements."""

    for node in tree.body:
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
            if isinstance(node.value.value, str):
                continue
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            continue
        if isinstance(node, ast.Pass):
            continue
        return False
    return True


def _node_names(node: ast.AST) -> tuple[str, ...]:
    """Identifiers a node binds or reaches: attributes, bare names, and import segments."""

    if isinstance(node, ast.Attribute):
        return (node.attr,)
    if isinstance(node, ast.Name):
        return (node.id,)
    if isinstance(node, ast.alias):
        return tuple(node.name.split("."))
    if isinstance(node, ast.ImportFrom) and node.module:
        return tuple(node.module.split("."))
    return ()


def _scan_effects(root: Path, owned_paths: tuple[str, ...]) -> _EffectScan:
    """Scan every owned file for effect vocabulary, leaving imports, and executable code."""

    owned = frozenset(owned_paths)
    hits: list[tuple[str, str, int, str]] = []
    opens: list[str] = []
    opaque: list[str] = []
    code: list[str] = []
    for path in owned_paths:
        data = (root / path).read_bytes()
        if b"\x00" in data[:8192]:
            opaque.append(path)
            continue
        text = data.decode("utf-8", "replace")
        for category, pattern in _EFFECT_PATTERNS.items():
            for match in pattern.finditer(text):
                line = text.count("\n", 0, match.start()) + 1
                hits.append((category, path, line, match.group(0)))
        if path.endswith(_UNPARSED_CODE_SUFFIXES):
            opens.append(f"{path}:unparsed-code")
            continue
        if not path.endswith(".py"):
            continue
        try:
            tree = ast.parse(text, filename=path)
        except SyntaxError:
            opens.append(f"{path}:syntax-error")
            continue
        if not _inert_python(tree):
            code.append(path)
        for node in ast.walk(tree):
            line = getattr(node, "lineno", 1)
            for name in _node_names(node):
                for category, effect_names in _AST_EFFECT_NAMES.items():
                    if name in effect_names:
                        hits.append((category, path, line, name))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                requests = [(alias.name, 0, ()) for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = tuple(alias.name for alias in node.names)
                requests = [(node.module or "", node.level, names)]
            else:
                continue
            for module, level, names in requests:
                if level == 0 and module.split(".")[0] in _STDLIB:
                    continue
                bound = any(
                    candidate in owned for candidate in _import_candidates(path, module, level)
                ) or (
                    bool(names)
                    and all(
                        any(
                            candidate in owned
                            for candidate in _import_candidates(
                                path, f"{module}.{name}" if module else name, level
                            )
                        )
                        for name in names
                    )
                )
                if not bound:
                    opens.append(f"{path}:{'.' * level}{module}")
    return _EffectScan(
        tuple(hits), tuple(sorted(set(opens))), tuple(opaque), tuple(code)
    )


def _closed_blocker(scan: _EffectScan, categories: tuple[str, ...]) -> str:
    """Return the exact reason the owner's effect surface is not closed for these categories."""

    if any(opened.endswith(":unparsed-code") for opened in scan.opens):
        return "unparsed executable code"
    if any(opened.endswith(":syntax-error") for opened in scan.opens):
        return "unparsable python"
    if scan.opens:
        return "unresolved or external import"
    if scan.opaque:
        return "opaque binary"
    if scan.code:
        return "executable owned code"
    if any(hit[0] == "dynamic" for hit in scan.hits):
        return "dynamic escape"
    if any(hit[0] in categories for hit in scan.hits):
        return "mapped effect construct"
    return ""


def _citation_holds(root: Path, owned_paths: tuple[str, ...], citation: tuple[str, int, str]) -> bool:
    path, line, needle = citation
    if path not in owned_paths:
        return False
    data = (root / path).read_bytes()
    if b"\x00" in data[:8192]:
        return False
    lines = data.decode("utf-8", "replace").splitlines()
    return 1 <= line <= len(lines) and bool(needle) and needle in lines[line - 1]


def _parse_behavioral(evidence: str) -> tuple[tuple[str, int, str], ...]:
    payload = json.loads(evidence[len(BEHAVIORAL_PREFIX):])
    if not isinstance(payload, list) or not payload:
        raise ValueError(_ERROR + "BEHAVIORAL_EVIDENCE_MALFORMED")
    citations = []
    for item in payload:
        if (
            not isinstance(item, list)
            or len(item) != 3
            or not isinstance(item[0], str)
            or type(item[1]) is not int
            or not isinstance(item[2], str)
        ):
            raise ValueError(_ERROR + "BEHAVIORAL_EVIDENCE_MALFORMED")
        citations.append((item[0], item[1], item[2]))
    return tuple(citations)


def _closed_categories(evidence: str) -> tuple[str, ...]:
    payload = json.loads(evidence[len(CLOSED_PREFIX):])
    if not isinstance(payload, dict) or set(payload) != {"categories"}:
        raise ValueError(_ERROR + "CLOSED_EVIDENCE_MALFORMED")
    categories = payload["categories"]
    if not isinstance(categories, list) or not all(isinstance(item, str) for item in categories):
        raise ValueError(_ERROR + "CLOSED_EVIDENCE_MALFORMED")
    return tuple(categories)


def behavioral_evidence(*citations: tuple[str, int, str]) -> str:
    """Encode exact source citations that establish one APPLIES cell."""

    return BEHAVIORAL_PREFIX + json.dumps(
        [[path, line, needle] for path, line, needle in citations],
        separators=(",", ":"),
        ensure_ascii=True,
    )


def closed_evidence(kind: str) -> str:
    """Encode a closed-surface DNE for one kind with a fixed category set."""

    return CLOSED_PREFIX + json.dumps(
        {"categories": list(_CLOSED_KIND_CATEGORIES[kind])},
        sort_keys=True,
        separators=(",", ":"),
    )


def _external_evidence_ok(
    root: Path, spec: SemanticOwnershipSpec, question: ScriptExampleOriginalKindQuestion, scans: dict
) -> None:
    """Re-derive behavioral and closed-surface evidence from the live owned bytes."""

    if question.evidence.startswith(BEHAVIORAL_PREFIX):
        if question.status != APPLIES:
            raise ValueError(_ERROR + "BEHAVIORAL_STATUS_INVALID:" + spec.object_id)
        for citation in _parse_behavioral(question.evidence):
            if not _citation_holds(root, tuple(spec.owned_paths), citation):
                raise ValueError(
                    _ERROR + "BEHAVIORAL_CITATION_DRIFT:" + spec.object_id + ":" + question.kind
                )
        return
    if question.status != DOES_NOT_APPLY or question.kind not in _CLOSED_KIND_CATEGORIES:
        raise ValueError(_ERROR + "CLOSED_STATUS_INVALID:" + spec.object_id)
    categories = _closed_categories(question.evidence)
    if categories != _CLOSED_KIND_CATEGORIES[question.kind]:
        raise ValueError(_ERROR + "CLOSED_CATEGORY_DRIFT:" + spec.object_id + ":" + question.kind)
    basis = _NON_EXECUTION_BASIS.get(spec.object_id)
    if basis is None:
        raise ValueError(_ERROR + "CLOSED_BASIS_MISSING:" + spec.object_id + ":" + question.kind)
    if basis not in _basis_text(spec):
        raise ValueError(_ERROR + "CLOSED_BASIS_DRIFT:" + spec.object_id + ":" + question.kind)
    if spec.object_id not in scans:
        scans[spec.object_id] = _scan_effects(root, tuple(spec.owned_paths))
    if _closed_blocker(scans[spec.object_id], categories):
        raise ValueError(_ERROR + "CLOSED_SURFACE_NOT_CLOSED:" + spec.object_id + ":" + question.kind)


