def _reviewed_source_snapshot(root: Path) -> tuple[tuple[str, str, str], ...]:
    """Read the five reviewed paths once, rejecting aliases and byte drift.

    Each call is one bounded snapshot. ``validate_source_partition`` takes an
    opening and closing snapshot so concurrent replacement cannot yield PASS
    from a mixture of source coordinates.  This is deliberately narrower than
    the 175-path ownership denominator: only source bytes actually re-reviewed
    for this catalog change are promoted into this pin set.
    """

    try:
        selected_root = Path(root).resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise ValueError(_ERROR + "REVIEWED_SOURCE_ROOT_UNAVAILABLE") from exc
    evidence: list[tuple[str, str, str]] = []
    for pin in REVIEWED_SOURCE_PINS:
        if (
            type(pin) is not tuple
            or len(pin) != 3
            or any(type(value) is not str for value in pin)
        ):
            raise ValueError(_ERROR + "REVIEWED_SOURCE_PIN_DENOMINATOR_DRIFT")
        object_id, path, expected_digest = pin
        relative = PurePosixPath(path)
        if relative.is_absolute() or ".." in relative.parts or "\\" in path:
            raise ValueError(_ERROR + "REVIEWED_SOURCE_PIN_DENOMINATOR_DRIFT")
        target = selected_root
        try:
            for part in relative.parts:
                target = target / part
                junction_check = getattr(target, "is_junction", None)
                if target.is_symlink() or (
                    callable(junction_check) and junction_check()
                ):
                    raise ValueError(
                        _ERROR
                        + "REVIEWED_SOURCE_ALIAS:"
                        + object_id
                        + ":"
                        + path
                    )
            resolved = target.resolve(strict=True)
            resolved.relative_to(selected_root)
            if not resolved.is_file():
                raise OSError(path)
            digest = "sha256:" + sha256(resolved.read_bytes()).hexdigest()
        except ValueError as exc:
            if str(exc).startswith(_ERROR + "REVIEWED_SOURCE_ALIAS:"):
                raise
            raise ValueError(
                _ERROR
                + "REVIEWED_SOURCE_UNAVAILABLE:"
                + object_id
                + ":"
                + path
            ) from exc
        except (OSError, RuntimeError) as exc:
            raise ValueError(
                _ERROR
                + "REVIEWED_SOURCE_UNAVAILABLE:"
                + object_id
                + ":"
                + path
            ) from exc
        if digest != expected_digest:
            raise ValueError(
                _ERROR
                + "REVIEWED_SOURCE_PIN_DIFFERS:"
                + object_id
                + ":"
                + path
            )
        evidence.append((object_id, path, digest))
    return tuple(evidence)




