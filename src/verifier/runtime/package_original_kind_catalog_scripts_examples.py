def _has_object_bypass(spec: SemanticOwnershipSpec) -> bool:
    return (
        spec.primary_kind == _OBJECT
        or _OBJECT in spec.specializations
        or any(decision.kind == _OBJECT for decision in spec.root_role_decisions)
    )


def _source_answers(spec: SemanticOwnershipSpec) -> dict[str, tuple[str, str]]:
    """Map each original kind the source names to its single literal status."""

    mentions = []
    if spec.primary_kind in ORIGINAL_NON_OBJECT_KINDS:
        mentions.append((spec.primary_kind, APPLIES, PRIMARY_EVIDENCE))
    mentions.extend(
        (kind, APPLIES, SPECIALIZATION_EVIDENCE)
        for kind in spec.specializations
        if kind in ORIGINAL_NON_OBJECT_KINDS
    )
    mentions.extend(
        (decision.kind, decision.status, decision.reason)
        for decision in spec.root_role_decisions
        if decision.kind in ORIGINAL_NON_OBJECT_KINDS
    )
    answers: dict[str, tuple[str, str]] = {}
    for kind, status, evidence in mentions:
        if kind == spec.primary_kind and status == DOES_NOT_APPLY:
            raise ValueError(_ERROR + "PRIMARY_REFUTED:" + spec.object_id)
        if kind in answers:
            raise ValueError(_ERROR + "SOURCE_ROLE_CONFLICT:" + spec.object_id)
        answers[kind] = (status, evidence)
    return answers


def validate_source_partition(
    specs: Iterable[SemanticOwnershipSpec],
    audits: Iterable[ScriptExampleOriginalKindAudit] | None = None,
    root: Path | None = None,
) -> tuple[SemanticOwnershipSpec, ...]:
    """Bind every literal answer to the exact current source; fail closed on drift."""

    selected = tuple(sorted(tuple(specs), key=lambda spec: spec.object_id))
    if any(type(spec) is not SemanticOwnershipSpec for spec in selected) or len(
        {spec.object_id for spec in selected}
    ) != len(selected):
        raise ValueError(_ERROR + "SOURCE_PARTITION_INVALID")
    rows = (
        SCRIPT_EXAMPLE_ORIGINAL_KIND_AUDITS if audits is None else tuple(audits)
    )
    by_id = {row.object_id: row for row in rows}
    if len(by_id) != len(rows):
        raise ValueError(_ERROR + "SOURCE_DENOMINATOR_DRIFT")
    source = {spec.object_id: spec for spec in selected}
    if set(source) != set(by_id):
        raise ValueError(_ERROR + "SOURCE_DENOMINATOR_DRIFT")
    repository = _REPO_ROOT if root is None else Path(root)
    opening_reviewed_sources = _reviewed_source_snapshot(repository)
    scans: dict[str, _EffectScan] = {}
    for object_id in sorted(by_id):
        row = by_id[object_id]
        spec = source[object_id]
        if _has_object_bypass(spec):
            raise ValueError(_ERROR + "OBJECT_BYPASS:" + object_id)
        if spec.primary_kind != row.expected_primary:
            raise ValueError(_ERROR + "PRIMARY_DRIFT:" + object_id)
        if (
            tuple(spec.owned_paths) != row.expected_owned_paths
            or owned_path_set_digest(spec.owned_paths) != row.expected_owned_path_set_digest
        ):
            raise ValueError(_ERROR + "PATH_DRIFT:" + object_id)
        answers = _source_answers(spec)
        if _spec_coordinate_digest(spec) != row.expected_source_coordinate_digest:
            raise ValueError(_ERROR + "SOURCE_COORDINATE_DRIFT:" + object_id)
        if row.scope_reason != _scope_reason(
            row.expected_representation_role,
            row.expected_necessity_reason,
            row.expected_consequence_boundary,
        ):
            raise ValueError(_ERROR + "REASON_DRIFT:" + object_id)
        if tuple(question.kind for question in row.questions) != ORIGINAL_NON_OBJECT_KINDS:
            raise ValueError(_ERROR + "REVIEW_DENOMINATOR_DRIFT:" + object_id)
        for question in row.questions:
            if question.evidence.startswith((BEHAVIORAL_PREFIX, CLOSED_PREFIX)):
                if question.kind in answers:
                    raise ValueError(_ERROR + "ACCUMULATED_ROLE_DRIFT:" + object_id)
                _external_evidence_ok(repository, spec, question, scans)
            else:
                expected = answers.get(question.kind, (UNRESOLVED, ""))
                if (question.status, question.evidence) != expected:
                    raise ValueError(_ERROR + "ACCUMULATED_ROLE_DRIFT:" + object_id)
                if (object_id, question.kind) in _CLOSED_CANDIDATES:
                    # A candidate is decided by its owner's basis alone: silently dropping
                    # a supported DNE is as much drift as promoting an unsupported one.
                    supported = object_id in _NON_EXECUTION_BASIS
                    if question.status != (DOES_NOT_APPLY if supported else UNRESOLVED):
                        raise ValueError(_ERROR + "CLOSED_DECISION_DRIFT:" + object_id + ":" + question.kind)
            if question.reason != _cell_reason(
                object_id,
                row.scope_reason,
                row.expected_owned_paths,
                question.kind,
                question.status,
                question.evidence,
            ):
                raise ValueError(_ERROR + "REASON_DRIFT:" + object_id)
    if _reviewed_source_snapshot(repository) != opening_reviewed_sources:
        raise ValueError(_ERROR + "REVIEWED_SOURCE_CHANGED_DURING_REVIEW")
    return selected


