def _cell_reason(
    object_id: str,
    scope_reason: str,
    owned_paths: tuple[str, ...],
    kind: str,
    status: str,
    evidence: str,
) -> str:
    """The one reason text a cell may carry, derived from its owner, status, and evidence."""

    basis = ""
    if evidence.startswith(CLOSED_PREFIX):
        basis = _NON_EXECUTION_BASIS.get(object_id, "")
    blocker = ""
    if status == UNRESOLVED and (object_id, kind) in _CLOSED_CANDIDATES:
        blocker = _downgrade_blocker(owned_paths)
    return _question_reason(scope_reason, kind, status, evidence, basis=basis, blocker=blocker)


def _override_cell(
    row: ScriptExampleOriginalKindAudit, kind: str, evidence: str
) -> ScriptExampleOriginalKindQuestion:
    """Build one overridden cell; closed-surface evidence lands only with a source basis."""

    if evidence.startswith(BEHAVIORAL_PREFIX):
        status = APPLIES
    elif row.object_id in _NON_EXECUTION_BASIS:
        status = DOES_NOT_APPLY
    else:
        status = UNRESOLVED
        evidence = ""
    return ScriptExampleOriginalKindQuestion(
        kind,
        status,
        evidence,
        _cell_reason(
            row.object_id,
            row.scope_reason,
            row.expected_owned_paths,
            kind,
            status,
            evidence,
        ),
    )


def _apply_overrides(rows: tuple[ScriptExampleOriginalKindAudit, ...]) -> tuple[ScriptExampleOriginalKindAudit, ...]:
    """Upgrade only UNRESOLVED cells named by an override; every override must land."""

    applied: set[tuple[str, str]] = set()
    rebuilt = []
    for row in rows:
        questions = []
        for question in row.questions:
            key = (row.object_id, question.kind)
            if question.status == UNRESOLVED and key in _EVIDENCE_OVERRIDES:
                question = _override_cell(row, question.kind, _EVIDENCE_OVERRIDES[key])
                applied.add(key)
            questions.append(question)
        rebuilt.append(replace(row, questions=tuple(questions)))
    if applied != set(_EVIDENCE_OVERRIDES):
        raise AssertionError("evidence override did not land on an unresolved cell")
    return tuple(rebuilt)


