def _canonical_digest(value: Any) -> str:
    return "sha256:" + sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    ).hexdigest()


def _coordinate_digest(
    object_id: str,
    primary: str,
    paths: tuple[str, ...],
    representation_role: str,
    necessity_reason: str,
    consequence_boundary: str,
    specializations: tuple[str, ...],
    root_role_decisions: tuple[tuple[str, str, str], ...],
    operands: tuple[tuple[str, tuple[str, ...]], ...],
) -> str:
    return _canonical_digest(
        {
            "object_id": object_id,
            "primary": primary,
            "owned_paths": list(paths),
            "representation_role": representation_role,
            "necessity_reason": necessity_reason,
            "consequence_boundary": consequence_boundary,
            "specializations": list(specializations),
            "root_role_decisions": [
                {"kind": kind, "status": status, "reason": reason}
                for kind, status, reason in root_role_decisions
            ],
            "operands": [[name, list(targets)] for name, targets in operands],
        }
    )


def _spec_coordinate_digest(spec: SemanticOwnershipSpec) -> str:
    return _coordinate_digest(
        spec.object_id,
        spec.primary_kind,
        tuple(spec.owned_paths),
        spec.representation_role,
        spec.necessity_reason,
        spec.consequence_boundary,
        tuple(spec.specializations),
        tuple(
            (decision.kind, decision.status, decision.reason)
            for decision in spec.root_role_decisions
        ),
        tuple(spec.operands),
    )


def _scope_reason(role: str, necessity: str, boundary: str) -> str:
    return role + " Necessity: " + necessity + " Consequence boundary: " + boundary


def _question(kind: str, status: str, evidence: str = "") -> tuple[str, str, str]:
    """Name one question literally; evidence is copied from source, never inferred."""

    return kind, status, evidence


def _question_reason(
    scope_reason: str,
    kind: str,
    status: str,
    evidence: str,
    basis: str = "",
    blocker: str = "",
) -> str:
    if status == APPLIES and evidence.startswith(BEHAVIORAL_PREFIX):
        cited = "; ".join(
            f"{path}:{line} `{needle}`" for path, line, needle in _parse_behavioral(evidence)
        )
        return (
            scope_reason
            + " Behavioral source evidence establishes applicability of "
            + kind
            + " for this exact object at "
            + cited
            + ". This establishes applicability only, not mechanism truth or "
            "higher-tier conformance."
        )
    if status == DOES_NOT_APPLY and evidence.startswith(CLOSED_PREFIX):
        return (
            scope_reason
            + " Closed effect surface: a live scan of every owned file and its owned "
            "imports found no unresolved import, no dynamic escape, and no "
            + ", ".join(_closed_categories(evidence))
            + " construct, so no effect of this owner declares "
            + kind
            + ". The scan is bounded to those named categories and proves no semantic "
            "absence beyond them. Source-owned non-execution basis for this owner, "
            "verbatim from its declaration: \""
            + basis
            + "\". The scan supports that basis and creates no refutation of its own."
        )
    if status == UNRESOLVED and blocker:
        return (
            scope_reason
            + " No owned-source decision establishes or refutes the "
            + kind
            + " original root for this exact object. Closed-surface downgrade: "
            + blocker
            + "."
        )
    if status == APPLIES and evidence == PRIMARY_EVIDENCE:
        return (
            scope_reason
            + " Source-declared primary_kind is "
            + kind
            + " for this exact object. This establishes applicability only, not "
            "mechanism truth or higher-tier conformance."
        )
    if status == APPLIES and evidence == SPECIALIZATION_EVIDENCE:
        return (
            scope_reason
            + " Source-declared specialization includes "
            + kind
            + " for this exact object. This establishes applicability only, not "
            "mechanism truth or higher-tier conformance."
        )
    if status == APPLIES:
        return (
            scope_reason
            + " Source-declared root_role_decision APPLIES for "
            + kind
            + ": "
            + evidence
            + " This establishes applicability only, not mechanism truth or "
            "higher-tier conformance."
        )
    if status == DOES_NOT_APPLY:
        return (
            scope_reason
            + " Source-declared root_role_decision DOES_NOT_APPLY for "
            + kind
            + ": "
            + evidence
        )
    return (
        scope_reason
        + " No owned-source decision in this partition establishes or refutes whether "
        "this exact object itself carries the "
        + kind
        + " original root. Operands, referenced inputs, outputs, and neighboring "
        "owners are not role equivalence, so "
        + kind
        + " remains UNRESOLVED."
    )


def _record(
    object_id: str,
    expected_primary: str,
    expected_owned_paths: tuple[str, ...],
    representation_role: str,
    necessity_reason: str,
    consequence_boundary: str,
    expected_specializations: tuple[str, ...],
    expected_root_role_decisions: tuple[tuple[str, str, str], ...],
    selections: tuple[tuple[str, str, str], ...],
) -> ScriptExampleOriginalKindAudit:
    if tuple(kind for kind, _status, _evidence in selections) != (
        ORIGINAL_NON_OBJECT_KINDS
    ):
        raise AssertionError(object_id + " original-kind question order differs")
    scope_reason = _scope_reason(representation_role, necessity_reason, consequence_boundary)
    questions = []
    for kind, status, evidence in selections:
        if status == APPLIES:
            if not evidence or (evidence == PRIMARY_EVIDENCE and kind != expected_primary):
                raise AssertionError(object_id + ":" + kind + " APPLIES evidence invalid")
        elif status == DOES_NOT_APPLY:
            if not evidence.strip():
                raise AssertionError(object_id + ":" + kind + " exclusion lacks a source reason")
        elif status == UNRESOLVED:
            if evidence:
                raise AssertionError(object_id + ":" + kind + " unresolved item carries evidence")
        else:
            raise AssertionError(object_id + " contains an invalid audit status")
        questions.append(
            ScriptExampleOriginalKindQuestion(
                kind,
                status,
                evidence,
                _question_reason(scope_reason, kind, status, evidence),
            )
        )
    paths = tuple(expected_owned_paths)
    specializations = tuple(expected_specializations)
    root_decisions = tuple(expected_root_role_decisions)
    return ScriptExampleOriginalKindAudit(
        object_id=object_id,
        expected_primary=expected_primary,
        expected_owned_paths=paths,
        expected_owned_path_set_digest=owned_path_set_digest(paths),
        expected_representation_role=representation_role,
        expected_necessity_reason=necessity_reason,
        expected_consequence_boundary=consequence_boundary,
        expected_specializations=specializations,
        expected_root_role_decisions=root_decisions,
        expected_source_coordinate_digest=_coordinate_digest(
            object_id,
            expected_primary,
            paths,
            representation_role,
            necessity_reason,
            consequence_boundary,
            specializations,
            root_decisions,
            (),
        ),
        scope_reason=scope_reason,
        questions=tuple(questions),
    )


