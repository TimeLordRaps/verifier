def validate_declared_source_bytes(root: Path) -> tuple[DeclaredSourceBinding, ...]:
    """Re-hash each declared-role source under ``root``; all-or-nothing."""

    audits = {row.object_id: row for row in RUNTIME_ORIGINAL_KIND_AUDITS}
    bound: set[tuple[str, str]] = set()
    for binding in _DECLARED_SOURCE_BINDINGS:
        label = binding.object_id + ":" + binding.path
        row = audits.get(binding.object_id)
        if row is None or binding.path not in row.expected_owned_paths:
            raise ValueError("RUNTIME_ORIGINAL_KIND_DECLARED_SOURCE_WRONG_OWNER:" + label)
        cell = (binding.object_id, binding.path)
        if cell in bound:
            raise ValueError("RUNTIME_ORIGINAL_KIND_DECLARED_SOURCE_DUPLICATE:" + label)
        bound.add(cell)
        try:
            data = (root / binding.path).read_bytes()
        except OSError as error:
            raise ValueError("RUNTIME_ORIGINAL_KIND_DECLARED_SOURCE_UNAVAILABLE:" + label) from error
        if "sha256:" + sha256(data).hexdigest() != binding.sha256:
            raise ValueError("RUNTIME_ORIGINAL_KIND_DECLARED_SOURCE_STALE:" + label)
    return _DECLARED_SOURCE_BINDINGS


