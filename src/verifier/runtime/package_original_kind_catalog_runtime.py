def _catalog_check() -> None:
    if len(RUNTIME_ORIGINAL_KIND_AUDITS) != 122:
        raise AssertionError("runtime original-kind object denominator differs")
    if len({row.object_id for row in RUNTIME_ORIGINAL_KIND_AUDITS}) != 122:
        raise AssertionError("runtime original-kind object ids overlap")
    profile_ids = {
        assignment.object_id for assignment in RUNTIME_PARTIAL_PROFILE.assignments
    }
    established = 0
    excluded = 0
    unresolved = 0
    for row in RUNTIME_ORIGINAL_KIND_AUDITS:
        if tuple(question.kind for question in row.questions) != (
            ORIGINAL_NON_OBJECT_KINDS
        ):
            raise AssertionError(row.object_id + " kind denominator differs")
        decided = tuple(
            question.kind
            for question in row.questions
            if question.status in {APPLIES, DOES_NOT_APPLY}
        )
        if bool(decided) != (row.object_id in profile_ids):
            raise AssertionError(row.object_id + " partial-profile membership differs")
        if any(not question.reason.strip() for question in row.questions):
            raise AssertionError(row.object_id + " contains a blank reason")
        established += sum(
            question.status == APPLIES for question in row.questions
        )
        excluded += sum(
            question.status == DOES_NOT_APPLY for question in row.questions
        )
        unresolved += sum(
            question.status == UNRESOLVED for question in row.questions
        )
    if established != 176:
        raise AssertionError("runtime original-kind APPLIES denominator differs")
    if len(_BEHAVIORAL_BY_CELL) != len(_BEHAVIORAL_EVIDENCE):
        raise AssertionError("runtime behavioral evidence cell is duplicated")
    if excluded != len(_EXCLUSION_REVIEWS):
        raise AssertionError("runtime original-kind DOES_NOT_APPLY denominator differs")
    if unresolved != 2872:
        raise AssertionError("runtime original-kind unresolved denominator differs")


_catalog_check()


def validate_runtime_review(root: Path) -> dict[str, dict[str, Any]]:
    """Return the audit only after source, bytes, and evidence set all bind.

    This is the sole API that re-binds BehavioralEvidence to file bytes under
    ``root``.  ``review_document`` checks source coordinates only, so a consumer
    that needs mechanism-level freshness must call this function.
    """

    validate_source_partition(current_source_partition())
    records = validate_behavioral_evidence(root)
    if len(records) != len(_BEHAVIORAL_BY_CELL) or {
        (record.object_id, record.kind) for record in records
    } != set(_BEHAVIORAL_BY_CELL):
        raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_SET_DRIFT")
    validate_declared_source_bytes(root)
    return review_document()


def review_document() -> dict[str, Any]:
    """Return the complete 120-by-25 audit without upgrading UNKNOWN items.

    Source coordinates are validated first, so a drifted ownership source fails
    closed on this default path.  Byte-level evidence needs ``validate_runtime_review``.
    """

    validate_source_partition(current_source_partition())
    profile_ids = {
        assignment.object_id for assignment in RUNTIME_PARTIAL_PROFILE.assignments
    }
    return {
        row.object_id: {
            "group": row.group,
            "expected_primary": row.expected_primary,
            "expected_owned_paths": list(row.expected_owned_paths),
            "expected_owned_path_set_digest": row.expected_owned_path_set_digest,
            "expected_source_coordinate_digest": row.expected_source_coordinate_digest,
            "scope_reason": row.scope_reason,
            "questions": {
                question.kind: {
                    "status": question.status,
                    "reason": question.reason,
                    "source_quote": question.source_quote,
                }
                for question in row.questions
            },
            "partial_profile_digest": (
                RUNTIME_PARTIAL_PROFILE.canonical_digest
                if row.object_id in profile_ids
                else None
            ),
            "claim_boundary": CLAIM_BOUNDARY,
        }
        for row in RUNTIME_ORIGINAL_KIND_AUDITS
    }


