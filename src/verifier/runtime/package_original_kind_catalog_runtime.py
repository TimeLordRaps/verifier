def _canonical_digest(value: Any) -> str:
    return "sha256:" + sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    ).hexdigest()


def _source_coordinate_digest(
    object_id: str,
    primary: str,
    paths: tuple[str, ...],
    representation_role: str,
    necessity_reason: str,
    consequence_boundary: str,
    specializations: tuple[str, ...],
    root_role_decisions: tuple[tuple[str, str, str], ...],
    operands: tuple[tuple[str, tuple[str, ...]], ...],
) -> str:
    return _canonical_digest(
        {
            "object_id": object_id,
            "primary": primary,
            "owned_paths": list(paths),
            "representation_role": representation_role,
            "necessity_reason": necessity_reason,
            "consequence_boundary": consequence_boundary,
            "specializations": list(specializations),
            "root_role_decisions": [
                {"kind": kind, "status": status, "reason": reason}
                for kind, status, reason in root_role_decisions
            ],
            "operands": [
                {"name": name, "targets": list(targets)}
                for name, targets in operands
            ],
        }
    )


