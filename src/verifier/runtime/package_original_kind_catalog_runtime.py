# Retired on adversarial re-audit; each cell is UNRESOLVED until new owned evidence
# is recorded.  A referenced input is not role equivalence, and a checker needs
# both a decision procedure and a replay or independent recheck in the anchored file.
#   vstd-hardware-receipt-assessor RECEIPT: the CLI loads, validates and reports
#     receipts from other modules; it constructs no receipt.
#   vstd-graph-topology-reader GRAPH: the graph type and topology analysis are
#     imported; the anchored file only reads and reports them.
#   vstd-dataset-provenance-policy GRAPH: ProvenanceHypergraph is defined in
#     verifier/data/models.py; policy.py consumes it through an import.
#   vstd-namespace-rule-engine VERIFIER: the anchored file has no replay or recheck.
#   vstd-self-polish-native-case-registry BENCH: the owned files define specimens and
#     expected outcomes but no scoring, coverage or budget; the replay controller
#     that would score them is outside this row.
_BEHAVIORAL_BY_CELL = {
    (record.object_id, record.kind): record for record in _BEHAVIORAL_EVIDENCE
}


def _question(
    kind: str,
    status: str,
    explicit_exclusion_reason: str = "",
) -> tuple[str, str, str]:
    """Construct no inferred meaning; callers literally name every question."""

    return kind, status, explicit_exclusion_reason


def _record(
    group: str,
    object_id: str,
    expected_primary: str,
    expected_owned_paths: tuple[str, ...],
    representation_role: str,
    necessity_reason: str,
    consequence_boundary: str,
    expected_specializations: tuple[str, ...],
    expected_root_role_decisions: tuple[tuple[str, str, str], ...],
    selections: tuple[tuple[str, str, str], ...],
    expected_operands: tuple[tuple[str, tuple[str, ...]], ...] = (),
) -> RuntimeOriginalKindAudit:
    if tuple(kind for kind, _status, _reason in selections) != (
        ORIGINAL_NON_OBJECT_KINDS
    ):
        raise AssertionError(object_id + " original-kind question order differs")
    if any(
        status not in {APPLIES, DOES_NOT_APPLY, UNRESOLVED}
        for _kind, status, _reason in selections
    ):
        raise AssertionError(object_id + " contains an invalid audit status")
    scope_reason = (
        representation_role
        + " Necessity: "
        + necessity_reason
        + " Consequence boundary: "
        + consequence_boundary
    )
    questions = []
    for kind, status, explicit_exclusion_reason in selections:
        evidence = _BEHAVIORAL_BY_CELL.get((object_id, kind))
        if evidence is not None and status != APPLIES:
            raise AssertionError(
                object_id + ":" + kind + " behavioral evidence requires APPLIES"
            )
        if status == APPLIES and evidence is not None:
            reason = (
                scope_reason
                + " Source-owned behavioral mechanism in "
                + evidence.path
                + " ("
                + evidence.sha256
                + "), anchored at \""
                + evidence.anchor
                + "\": "
                + evidence.mechanism
                + ". This establishes applicability only, not mechanism truth or "
                  "higher-tier conformance."
            )
        elif status == APPLIES:
            reason = (
                scope_reason
                + " The source-owned aggregate declaration explicitly establishes "
                + kind
                + " as this row's original primary or accumulated role. This "
                  "establishes applicability only, not mechanism truth or "
                  "higher-tier conformance."
            )
        elif status == DOES_NOT_APPLY:
            if not explicit_exclusion_reason.strip():
                raise AssertionError(
                    object_id + ":" + kind + " exclusion lacks a source reason"
                )
            if (object_id, kind) not in _EXCLUSION_REVIEWS:
                raise AssertionError(
                    object_id + ":" + kind + " exclusion lacks a counterexample review"
                )
            reason = (
                scope_reason
                + " Verbatim consequence-boundary exclusion for "
                + kind
                + ": \""
                + explicit_exclusion_reason
                + "\". "
                + _EXCLUSION_REVIEWS[(object_id, kind)]
            )
        else:
            if explicit_exclusion_reason:
                raise AssertionError(
                    object_id + ":" + kind + " unresolved item carries exclusion"
                )
            reason = (
                scope_reason
                + " No feature-near source decision establishes or refutes whether "
                  "this exact row itself is "
                + _KIND_CRITERIA[kind]
                + ". Referenced inputs, outputs, subjects, consequences, and "
                  "operands are not role equivalence, and output-scope limits such "
                  "as establishes-no or does-not-prove are not exclusions, so "
                + kind
                + " remains UNRESOLVED. Exact blocker: no root_role_decisions entry "
                  "for this kind in the semantic-ownership declaration, and no "
                  "verbatim boundary sentence denying this row's identity or "
                  "defining operation; the source annotation needed is "
                  "RootRoleDecision('"
                + kind
                + "', APPLIES or DOES_NOT_APPLY, reason) on this object's ownership spec."
            )
        questions.append(
            RuntimeOriginalKindQuestion(
                kind,
                status,
                reason,
                explicit_exclusion_reason if status == DOES_NOT_APPLY else "",
            )
        )
    paths = tuple(expected_owned_paths)
    root_decisions = tuple(expected_root_role_decisions)
    operands = tuple(
        (name, tuple(targets)) for name, targets in expected_operands
    )
    return RuntimeOriginalKindAudit(
        group=group,
        object_id=object_id,
        expected_primary=expected_primary,
        expected_owned_paths=paths,
        expected_owned_path_set_digest=owned_path_set_digest(paths),
        expected_representation_role=representation_role,
        expected_necessity_reason=necessity_reason,
        expected_consequence_boundary=consequence_boundary,
        expected_specializations=tuple(expected_specializations),
        expected_root_role_decisions=root_decisions,
        expected_operands=operands,
        expected_source_coordinate_digest=_source_coordinate_digest(
            object_id,
            expected_primary,
            paths,
            representation_role,
            necessity_reason,
            consequence_boundary,
            tuple(expected_specializations),
            root_decisions,
            operands,
        ),
        scope_reason=scope_reason,
        questions=tuple(questions),
    )


