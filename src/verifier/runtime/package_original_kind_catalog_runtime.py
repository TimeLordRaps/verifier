def validate_source_partition(
    specs: Iterable[SemanticOwnershipSpec],
) -> tuple[SemanticOwnershipSpec, ...]:
    """Bind the literal audit to one exact aggregate-local source partition."""

    selected = tuple(sorted(tuple(specs), key=lambda spec: spec.object_id))
    if (
        any(type(spec) is not SemanticOwnershipSpec for spec in selected)
        or len({spec.object_id for spec in selected}) != len(selected)
    ):
        raise ValueError("RUNTIME_ORIGINAL_KIND_SOURCE_PARTITION_INVALID")
    claimed = [path for spec in selected for path in spec.owned_paths]
    if len(claimed) != len(set(claimed)):
        raise ValueError("RUNTIME_ORIGINAL_KIND_SOURCE_OWNERSHIP_OVERLAP")
    audits = {row.object_id: row for row in RUNTIME_ORIGINAL_KIND_AUDITS}
    source = {spec.object_id: spec for spec in selected}
    if set(source) != set(audits):
        raise ValueError("RUNTIME_ORIGINAL_KIND_SOURCE_DENOMINATOR_DRIFT")
    for object_id, row in audits.items():
        spec = source[object_id]
        if spec.primary_kind != row.expected_primary:
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_SOURCE_PRIMARY_DRIFT:" + object_id
            )
        if tuple(spec.owned_paths) != row.expected_owned_paths:
            raise ValueError("RUNTIME_ORIGINAL_KIND_SOURCE_PATH_DRIFT:" + object_id)
        if tuple(spec.operands) != row.expected_operands:
            raise ValueError("RUNTIME_ORIGINAL_KIND_SOURCE_OPERAND_DRIFT:" + object_id)
        source_applies = set()
        if spec.primary_kind in ORIGINAL_NON_OBJECT_KINDS:
            source_applies.add(spec.primary_kind)
        source_applies.update(
            kind
            for kind in spec.specializations
            if kind in ORIGINAL_NON_OBJECT_KINDS
        )
        source_dne = {
            decision.kind
            for decision in spec.root_role_decisions
            if decision.kind in ORIGINAL_NON_OBJECT_KINDS
            and decision.status == DOES_NOT_APPLY
        }
        source_applies.update(
            decision.kind
            for decision in spec.root_role_decisions
            if decision.kind in ORIGINAL_NON_OBJECT_KINDS
            and decision.status == APPLIES
        )
        if source_applies & source_dne:
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_SOURCE_ROLE_CONFLICT:" + object_id
            )
        if _spec_source_coordinate_digest(spec) != row.expected_source_coordinate_digest:
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_SOURCE_COORDINATE_DRIFT:" + object_id
            )
        review = {question.kind: question for question in row.questions}
        if set(review) != set(ORIGINAL_NON_OBJECT_KINDS):
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_REVIEW_DENOMINATOR_DRIFT:" + object_id
            )
        review_applies = {
            kind for kind, question in review.items() if question.status == APPLIES
        }
        review_dne = {
            kind
            for kind, question in review.items()
            if question.status == DOES_NOT_APPLY
        }
        behavioral_applies = {
            kind for owner, kind in _BEHAVIORAL_BY_CELL if owner == object_id
        }
        if behavioral_applies & source_applies:
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_BEHAVIORAL_DUPLICATES_DECLARED:" + object_id
            )
        if review_applies != (source_applies | behavioral_applies) or not (
            source_dne <= review_dne
        ):
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_ACCUMULATED_ROLE_DRIFT:" + object_id
            )
        boundary_dne = review_dne - source_dne
        reviewed = {kind for owner, kind in _EXCLUSION_REVIEWS if owner == object_id}
        if reviewed != boundary_dne:
            raise ValueError(
                "RUNTIME_ORIGINAL_KIND_EXCLUSION_REVIEW_DRIFT:" + object_id
            )
        for kind in sorted(boundary_dne):
            quote = review[kind].source_quote
            if not quote or quote not in spec.consequence_boundary:
                raise ValueError(
                    "RUNTIME_ORIGINAL_KIND_BOUNDARY_QUOTE_DRIFT:"
                    + object_id
                    + ":"
                    + kind
                )
    return selected


def validate_behavioral_evidence(root: Path) -> tuple[BehavioralEvidence, ...]:
    """Re-bind every behavioral APPLIES to the current bytes under ``root``.

    The check is all-or-nothing: each record is validated before the tuple is
    returned, so one stale, substituted, or drifted record rejects the basis.
    """

    audits = {row.object_id: row for row in RUNTIME_ORIGINAL_KIND_AUDITS}
    records = tuple(_BEHAVIORAL_EVIDENCE)
    cells: set[tuple[str, str]] = set()
    for record in records:
        cell = (record.object_id, record.kind)
        label = record.object_id + ":" + record.kind
        row = audits.get(record.object_id)
        if row is None or record.kind not in ORIGINAL_NON_OBJECT_KINDS:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_CELL_INVALID:" + label)
        if cell in cells:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_DUPLICATE:" + label)
        cells.add(cell)
        question = next(item for item in row.questions if item.kind == record.kind)
        if question.status != APPLIES:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_CELL_NOT_APPLIES:" + label)
        if record.path not in row.expected_owned_paths:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_WRONG_SOURCE:" + label)
        # An empty string is a substring of every text, so blank anchors must be
        # rejected explicitly rather than relying on the containment check below.
        if not record.anchor.strip() or not record.mechanism.strip():
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_BLANK:" + label)
        try:
            data = (root / record.path).read_bytes()
        except OSError as error:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_UNAVAILABLE:" + label) from error
        if "sha256:" + sha256(data).hexdigest() != record.sha256:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_STALE:" + label)
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError as error:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_ANCHOR_DRIFT:" + label) from error
        if record.anchor not in text:
            raise ValueError("RUNTIME_ORIGINAL_KIND_EVIDENCE_ANCHOR_DRIFT:" + label)
    return records


