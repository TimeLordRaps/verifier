def _profile_scope_reason(row: RuntimeOriginalKindAudit) -> str:
    """Avoid multiplying an already source-bound scope into every cell."""

    if any((row.object_id, question.kind) in _BEHAVIORAL_BY_CELL
           for question in row.questions):
        return (
            "Full review scope is bound by source coordinate "
            + row.expected_source_coordinate_digest
            + "."
        )
    return row.scope_reason


def _profile_decision(
    row: RuntimeOriginalKindAudit,
    question: RuntimeOriginalKindQuestion,
) -> OriginalKindDecision:
    """Seal a behavioral cell to its exact positive-witness source path."""

    evidence = _BEHAVIORAL_BY_CELL.get((row.object_id, question.kind))
    if evidence is None:
        return OriginalKindDecision(
            question.kind, question.status, question.reason
        )
    return OriginalKindDecision(
        question.kind,
        question.status,
        evidence.mechanism,
        (evidence.path,),
    )


