def _apply_obligation_retention(
    row: RetainedOriginalKindAudit,
) -> RetainedOriginalKindAudit:
    """Retain open obligations at an executable boundary without claiming effects."""
    boundary = _OBLIGATION_RETENTION_BOUNDARIES.get(row.object_id)
    reason_only = set(_REASON_ONLY_OBLIGATION_RETENTION.get(row.object_id, ()))
    if boundary is None and not reason_only:
        return row
    if boundary is None:
        path = None
        line = None
        source_name = None
        boundary_label = None
    else:
        path_index, line = boundary
        path = row.expected_owned_paths[path_index]
        source_name = Path(path).name
        boundary_label = _OBLIGATION_RETENTION_BOUNDARY_LABELS.get(
            row.object_id,
            "imported VerificationSession evaluation",
        )

    def retain(question: RetainedOriginalKindQuestion) -> RetainedOriginalKindQuestion:
        if question.status != UNRESOLVED:
            return question
        if boundary is None:
            if question.kind not in reason_only:
                return question
            reason = (
                f"The sole reasons.vstd conservatively retains {question.kind} for "
                f"vstd-package-object because its static owned artifacts do not prove "
                f"inapplicability; no {question.kind} effect, mechanism, authority or checker PASS is claimed."
            )
        else:
            reason = (
                f"{source_name}:{line} crosses the {boundary_label} boundary, so "
                f"{question.kind} effects are not proved unreachable. The sole reasons.vstd "
                f"retains {question.kind}; no such effect, authority or checker PASS is claimed."
            )
        return RetainedOriginalKindQuestion(question.kind, APPLIES, path, line, reason)

    questions = tuple(
        retain(question)
        for question in row.questions
    )
    if any(len(question.reason) > 260 for question in questions):
        raise AssertionError(row.object_id + " retained reason is too long")
    return RetainedOriginalKindAudit(
        object_id=row.object_id,
        expected_primary=row.expected_primary,
        expected_owned_paths=row.expected_owned_paths,
        expected_owned_path_set_digest=row.expected_owned_path_set_digest,
        source_sha256=row.source_sha256,
        scope_reason=row.scope_reason,
        questions=questions,
    )


RETAINED_ORIGINAL_KIND_AUDITS = tuple(
    _apply_obligation_retention(row)
    for row in _SOURCE_AUDITED_ORIGINAL_KIND_AUDITS
)


def _profile_assignments() -> tuple[OriginalKindAssignment, ...]:
    """Seal every row with its non-UNRESOLVED decisions only."""
    return tuple(
        OriginalKindAssignment(
            object_id=row.object_id,
            expected_primary=row.expected_primary,
            expected_owned_paths=row.expected_owned_paths,
            expected_owned_path_set_digest=row.expected_owned_path_set_digest,
            scope_reason=row.scope_reason,
            decisions=tuple(
                OriginalKindDecision(question.kind, question.status, question.reason)
                for question in row.questions
                if question.status != UNRESOLVED
            ),
        )
        for row in RETAINED_ORIGINAL_KIND_AUDITS
    )


