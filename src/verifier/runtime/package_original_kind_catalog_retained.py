@dataclass(frozen=True)
class RetainedOriginalKindQuestion:
    """One decision; path and line are absent for UNKNOWN or reason-only retention."""

    kind: str
    status: str
    path: str | None
    line: int | None
    reason: str


@dataclass(frozen=True)
class RetainedOriginalKindAudit:
    """One exact row, its owned-file digests, and all 25 kind decisions."""

    object_id: str
    expected_primary: str
    expected_owned_paths: tuple[str, ...]
    expected_owned_path_set_digest: str
    source_sha256: tuple[str, ...]
    scope_reason: str
    questions: tuple[RetainedOriginalKindQuestion, ...]


def _cell(
    kind: str,
    status: str,
    path_index: int | None,
    line: int | None,
    reason: str,
) -> tuple[str, str, int | None, int | None, str]:
    """Hold one literal cell; its evidence is validated when its row is recorded."""
    return kind, status, path_index, line, reason


def _record(
    object_id: str,
    expected_primary: str,
    expected_owned_paths: tuple[str, ...],
    source_sha256: tuple[str, ...],
    scope_reason: str,
    cells: tuple[tuple[str, str, int | None, int | None, str], ...],
) -> RetainedOriginalKindAudit:
    """Reject any row that is not exactly 25 ordered, evidence-bound cells."""
    if tuple(cell[0] for cell in cells) != ORIGINAL_NON_OBJECT_KINDS:
        raise AssertionError(object_id + " original-kind cell order or denominator differs")
    if len(source_sha256) != len(expected_owned_paths):
        raise AssertionError(object_id + " source digest count differs from owned paths")
    questions = []
    for kind, status, path_index, line, reason in cells:
        if status not in {APPLIES, DOES_NOT_APPLY, UNRESOLVED}:
            raise AssertionError(object_id + " contains an unknown status")
        if status == UNRESOLVED:
            if path_index is not None or line is not None:
                raise AssertionError(object_id + " UNRESOLVED cell cites evidence")
            path = None
        else:
            if type(path_index) is not int or not 0 <= path_index < len(expected_owned_paths):
                raise AssertionError(object_id + " cell cites a path it does not own")
            if type(line) is not int or line < 1:
                raise AssertionError(object_id + " cell line is not a 1-indexed line")
            if status == DOES_NOT_APPLY and line == 1:
                raise AssertionError(object_id + " DOES_NOT_APPLY cites line 1, a docstring or primary declaration")
            path = expected_owned_paths[path_index]
        if not reason.strip() or len(reason) > 260:
            raise AssertionError(object_id + " reason is blank or too long")
        questions.append(RetainedOriginalKindQuestion(kind, status, path, line, reason))
    primary = next((q for q in questions if q.kind == expected_primary), None)
    if primary is not None and primary.status == DOES_NOT_APPLY:
        raise AssertionError(object_id + " refutes its own primary kind")
    return RetainedOriginalKindAudit(
        object_id=object_id,
        expected_primary=expected_primary,
        expected_owned_paths=expected_owned_paths,
        expected_owned_path_set_digest=owned_path_set_digest(expected_owned_paths),
        source_sha256=source_sha256,
        scope_reason=scope_reason,
        questions=tuple(questions),
    )


_NON_SUBSTANTIVE_LINE = re.compile(
    r"""^\s*(?:[A-Z][A-Z0-9_]*\s*(?::[^=]+)?=\s*["']|#|import\s|from\s+\S+\s+import\s|["']subject_kind["']\s*:|pass\s*$|\.\.\.\s*$)"""
)


def _docstring_or_import_lines(text: str) -> set[int]:
    """Collect lines owned by imports, pass or bare-constant statements, and docstrings."""
    covered: set[int] = set()
    for node in ast.walk(ast.parse(text)):
        if isinstance(node, (ast.Import, ast.ImportFrom, ast.Pass)) or (
            isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
        ):
            covered.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
    return covered


def refutation_line_is_substantive(root: Path, path: str, line: int) -> bool:
    """Return False for a blank, comment, import, docstring, label, or empty-marker line.

    True means only that the line is not a referent. It does not prove that the cited
    kind is absent from the subject; the exclusion or closed boundary must still be cited.
    """
    text = (root / path).read_text(encoding="utf-8")
    lines = text.splitlines()
    if not 1 <= line <= len(lines) or not lines[line - 1].strip():
        return False
    if _NON_SUBSTANTIVE_LINE.match(lines[line - 1]):
        return False
    return line not in _docstring_or_import_lines(text)


