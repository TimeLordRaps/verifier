"""Source-bound original-kind applicability audit of the 27 retained package rows.

Terminology: command-line interface (CLI); central processing unit (CPU);
directed acyclic graph (DAG); JavaScript Object Notation (JSON); Secure Hash
Algorithm 256-bit (SHA-256); Coordinated Universal Time (UTC).

Every cell is one of 675 decisions (27 rows by the 25 original non-OBJECT kinds).
An APPLIES or DOES_NOT_APPLY cell cites one 1-indexed line of a file that its row owns,
and each row records the SHA-256 digest of every owned file it was reviewed against. A
change to an owned file makes that row stale until it is re-audited. A manifest operand,
primary label, specialization, line-1 docstring, import, comment, empty marker, or
NOT_ESTABLISHED gap is never a refutation. A DOES_NOT_APPLY cell must cite a substantive
line whose exhaustive exclusion or closed boundary rules out that specific kind; absence
and complement are not refutations. UNRESOLVED names missing source evidence and is never
coerced to a source-mechanism claim. Separately, the sole ``reasons.vstd`` may
conservatively retain an obligation as APPLIES where an executable boundary prevents
proof of unreachability. Such retention does not assert the corresponding effect. This
is partial applicability evidence; it is not package closure, polish conformance, or
mechanism truth.
"""

