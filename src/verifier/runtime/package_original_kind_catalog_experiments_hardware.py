OVERLAY_SOURCE_TOTALS = {"applies": 105, "dne": 27, "unresolved": 1418}
OVERLAY_TOTALS = {"applies": 56, "dne": 329}
OVERLAY_DOWNGRADE_TOTALS = {"dne": 381}
PRIOR_OVERLAY_DNE_CLAIMS = 710
EFFECTIVE_TOTALS = {"applies": 161, "dne": 356, "unresolved": 1033}


def _overlay_check(overlay: dict[str, dict[str, Any]] = BEHAVIOR_OVERLAY) -> None:
    """Fail closed unless the overlay touches only UNRESOLVED source cells."""

    rows = {row.object_id: row for row in EXPERIMENTS_HARDWARE_ORIGINAL_KIND_AUDITS}
    if set(overlay) != set(rows):
        raise AssertionError("behavior overlay denominator differs")
    applies_total = 0
    dne_total = 0
    blocked_total = 0
    for object_id, entry in overlay.items():
        source = {question.kind: question.status for question in rows[object_id].questions}
        overlay_applies = [kind for kind, _reason, _cites in entry["applies"]]
        overlay_dne = list(entry["dne"])
        if len(set(overlay_applies)) != len(overlay_applies) or len(set(overlay_dne)) != len(overlay_dne):
            raise AssertionError(object_id + " overlay repeats a kind")
        if set(overlay_applies) & set(overlay_dne):
            raise AssertionError(object_id + " overlay both applies and excludes a kind")
        for kind in (*overlay_applies, *overlay_dne):
            if kind not in ORIGINAL_NON_OBJECT_KINDS:
                raise AssertionError(object_id + " overlay names an unknown kind")
            if source[kind] != UNRESOLVED:
                raise AssertionError(object_id + " overlay overrides source decision " + kind)
        for kind, reason, cites in entry["applies"]:
            if not reason.strip() or not cites:
                raise AssertionError(object_id + " overlay applies without reason or citation")
        if overlay_dne and not entry["auditor_closure"].strip():
            raise AssertionError(object_id + " overlay excludes without closure text")
        if overlay_dne and not str(entry.get("identity_basis", "")).strip():
            raise AssertionError(object_id + " overlay excludes without identity basis")
        blocked = entry["blocked"]
        unresolved_kinds = {kind for kind, status in source.items() if status == UNRESOLVED}
        if set(blocked) & set(overlay_dne) or not set(blocked) <= unresolved_kinds:
            raise AssertionError(object_id + " overlay blocker names a retained or source-decided kind")
        if any(not isinstance(code, str) or not code.strip() for code in blocked.values()):
            raise AssertionError(object_id + " overlay blocker lacks an exact code")
        applies_total += len(overlay_applies)
        dne_total += len(overlay_dne)
        blocked_total += len(blocked)
    if (applies_total, dne_total) != (OVERLAY_TOTALS["applies"], OVERLAY_TOTALS["dne"]):
        raise AssertionError("behavior overlay decision denominator differs")
    if (dne_total + blocked_total, blocked_total) != (
        PRIOR_OVERLAY_DNE_CLAIMS,
        OVERLAY_DOWNGRADE_TOTALS["dne"],
    ):
        raise AssertionError("behavior overlay downgrade denominator differs")
    source_counts = (
        sum(question.status == APPLIES for row in rows.values() for question in row.questions),
        sum(question.status == DOES_NOT_APPLY for row in rows.values() for question in row.questions),
        sum(question.status == UNRESOLVED for row in rows.values() for question in row.questions),
    )
    if source_counts != (
        OVERLAY_SOURCE_TOTALS["applies"],
        OVERLAY_SOURCE_TOTALS["dne"],
        OVERLAY_SOURCE_TOTALS["unresolved"],
    ):
        raise AssertionError("source decision denominator differs")
    effective = (
        source_counts[0] + applies_total,
        source_counts[1] + dne_total,
        source_counts[2] - applies_total - dne_total,
    )
    if effective != (
        EFFECTIVE_TOTALS["applies"],
        EFFECTIVE_TOTALS["dne"],
        EFFECTIVE_TOTALS["unresolved"],
    ):
        raise AssertionError("effective decision denominator differs")


_overlay_check()


def effective_review_document(
    overlay: dict[str, dict[str, Any]] = BEHAVIOR_OVERLAY,
) -> dict[str, dict[str, str]]:
    """Return statuses after the overlay, computed only after full validation."""

    _overlay_check(overlay)
    result: dict[str, dict[str, str]] = {}
    for row in EXPERIMENTS_HARDWARE_ORIGINAL_KIND_AUDITS:
        entry = overlay[row.object_id]
        decided = {kind: APPLIES for kind, _reason, _cites in entry["applies"]}
        decided.update({kind: DOES_NOT_APPLY for kind in entry["dne"]})
        result[row.object_id] = {
            question.kind: (
                decided.get(question.kind, question.status)
                if question.status == UNRESOLVED
                else question.status
            )
            for question in row.questions
        }
    return result


