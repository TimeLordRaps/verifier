def validate_source_partition(
    specs: Iterable[SemanticOwnershipSpec],
) -> tuple[SemanticOwnershipSpec, ...]:
    """Bind literal reviews to the exact experiments and hardware partitions."""

    selected = tuple(sorted(tuple(specs), key=lambda spec: spec.object_id))
    if (
        any(type(spec) is not SemanticOwnershipSpec for spec in selected)
        or len({spec.object_id for spec in selected}) != len(selected)
    ):
        raise ValueError("EXPERIMENTS_HARDWARE_SOURCE_PARTITION_INVALID")
    audits = {
        row.object_id: row for row in EXPERIMENTS_HARDWARE_ORIGINAL_KIND_AUDITS
    }
    source = {spec.object_id: spec for spec in selected}
    if set(source) != set(audits):
        raise ValueError("EXPERIMENTS_HARDWARE_SOURCE_DENOMINATOR_DRIFT")
    for object_id, row in audits.items():
        spec = source[object_id]
        if spec.primary_kind != row.expected_primary:
            raise ValueError(
                "EXPERIMENTS_HARDWARE_SOURCE_PRIMARY_DRIFT:" + object_id
            )
        if tuple(spec.owned_paths) != row.expected_owned_paths:
            raise ValueError(
                "EXPERIMENTS_HARDWARE_SOURCE_PATH_DRIFT:" + object_id
            )
        source_applies = set()
        if spec.primary_kind in ORIGINAL_NON_OBJECT_KINDS:
            source_applies.add(spec.primary_kind)
        source_applies.update(
            kind
            for kind in spec.specializations
            if kind in ORIGINAL_NON_OBJECT_KINDS
        )
        source_dne = {
            decision.kind
            for decision in spec.root_role_decisions
            if decision.kind in ORIGINAL_NON_OBJECT_KINDS
            and decision.status == DOES_NOT_APPLY
        }
        source_applies.update(
            decision.kind
            for decision in spec.root_role_decisions
            if decision.kind in ORIGINAL_NON_OBJECT_KINDS
            and decision.status == APPLIES
        )
        if source_applies & source_dne:
            raise ValueError(
                "EXPERIMENTS_HARDWARE_SOURCE_ROLE_CONFLICT:" + object_id
            )
        if _spec_source_coordinate_digest(spec) != row.expected_source_coordinate_digest:
            raise ValueError(
                "EXPERIMENTS_HARDWARE_SOURCE_COORDINATE_DRIFT:" + object_id
            )
        review = {question.kind: question for question in row.questions}
        if set(review) != set(ORIGINAL_NON_OBJECT_KINDS):
            raise ValueError(
                "EXPERIMENTS_HARDWARE_REVIEW_DENOMINATOR_DRIFT:" + object_id
            )
        review_applies = {
            kind for kind, question in review.items() if question.status == APPLIES
        }
        review_dne = {
            kind
            for kind, question in review.items()
            if question.status == DOES_NOT_APPLY
        }
        if review_applies != source_applies or review_dne != source_dne:
            raise ValueError(
                "EXPERIMENTS_HARDWARE_ACCUMULATED_ROLE_DRIFT:" + object_id
            )
    return selected


