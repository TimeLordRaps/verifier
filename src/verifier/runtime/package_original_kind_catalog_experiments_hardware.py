"""Original-kind audit for experiments and hardware-interop ownership rows.

Terminology: command-line interface (CLI); conjunctive normal form (CNF);
Compute Unified Device Architecture (CUDA); directed acyclic graph (DAG);
graphics processing unit (GPU); hash-based message authentication code (HMAC);
Hypertext Transfer Protocol (HTTP); machine learning (ML); random number
generator (RNG); Boolean satisfiability problem (SAT); unsatisfiable (UNSAT);
uniform resource locator (URL); Coordinated Universal Time (UTC).

This catalog covers exactly the imported experiments and hardware-interop
semantic-ownership partitions. Every object lists all 25 original non-OBJECT
questions literally. Explicit root-role decisions are preserved cumulatively,
including their object-specific exclusion reasons. No omitted role, primary
absence, filename, path, complement, or OBJECT label creates a decision.
Unestablished questions remain UNRESOLVED.

The sealed profile is partial. It proves neither full-package closure,
experiment validity, physical truth, polish conformance, release, nor
deployment. JavaScript Object Notation (JSON); Verifier Standard (VSTD).

BEHAVIOR_OVERLAY adds decisions only for source UNRESOLVED cells. Each
overlay object is digest-bound to the working-tree bytes of its evidence
set (owned paths, declared helpers, and one hop of local imports). APPLIES
needs a cited line carrying a kind token. DOES_NOT_APPLY is retained only
with a positive source-owned identity basis and a mechanism-level closure
for that kind; zero keyword hits support it but never establish it. A claim
that fails a mechanical gate over the transitive local import closure
(keyword or synonym hits, process launches, callable-parameter invocations,
binary bytes, stale source) is downgraded to UNRESOLVED, with its exact
blocker recorded in `blocked`. The sealed profile and CLAIM_BOUNDARY are
unchanged, so the aggregate catalog closure is not affected by the overlay.
"""

