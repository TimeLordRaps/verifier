class _Refuted(Exception):
    pass


class _Unavailable(Exception):
    pass


@dataclass(frozen=True)
class _RunObservation:
    returncode: int | None
    timed_out: bool
    overflow: bool
    stdout_digest: str | None
    stderr_digest: str | None
    junit_raw: bytes | None
    trace_raw: bytes | None


def canonical_bytes(value: Any) -> bytes:
    """Return the canonical bytes required for a selected manifest."""

    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def bytes_digest(raw: bytes) -> str:
    return "sha256:" + hashlib.sha256(raw).hexdigest()


def mechanism_digest() -> str:
    """Digest the loaded mechanism source; this is not a trust assertion."""

    return bytes_digest(Path(__file__).read_bytes())


def _valid_hash(value: Any) -> bool:
    return type(value) is str and _HASH.fullmatch(value) is not None


def _decode(raw: bytes, *, limit: int, code: str) -> dict[str, Any]:
    if type(raw) is not bytes:
        raise _Refuted(code)
    if len(raw) > limit:
        raise _Unavailable(code.replace("INVALID", "CAPACITY_EXHAUSTED"))

    def pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in items:
            if key in result:
                raise _Refuted(code)
            result[key] = value
        return result

    try:
        value = json.loads(
            raw.decode("utf-8"), object_pairs_hook=pairs,
            parse_constant=lambda _: (_ for _ in ()).throw(_Refuted(code)),
        )
    except _Refuted:
        raise
    except (UnicodeError, json.JSONDecodeError, ValueError, TypeError) as exc:
        raise _Refuted(code) from exc
    if type(value) is not dict or canonical_bytes(value) != raw:
        raise _Refuted(code)
    return value


def _path(value: Any) -> str:
    if type(value) is not str or not value or len(value) > 512:
        raise _Refuted("MANIFEST_PATH_INVALID")
    if ("\\" in value or ":" in value or value.startswith("/")
            or unicodedata.normalize("NFC", value) != value
            or any(part in {"", ".", ".."} for part in value.split("/"))
            or str(PurePosixPath(value)) != value):
        raise _Refuted("MANIFEST_PATH_INVALID")
    try:
        value.encode("utf-8", "strict")
    except UnicodeError as exc:
        raise _Refuted("MANIFEST_PATH_INVALID") from exc
    return value


def _recursive_test_path(value: str) -> bool:
    return PurePosixPath(value).name.startswith("test_self_polish")


def _node_id(value: Any, test_path: str) -> str:
    if (type(value) is not str or not value.startswith(test_path + "::")
            or len(value) > 1024 or value == test_path + "::"
            or any(ord(char) < 32 or ord(char) == 127 for char in value)
            or any(char in value for char in ("*", "?", "\\"))):
        raise _Refuted("PYTEST_NODE_ID_INVALID")
    if _recursive_test_path(test_path):
        raise _Refuted("RECURSIVE_SELF_POLISH_TEST_REFUSED")
    return value


def _resolve_file(root: Path, relative: str) -> Path:
    try:
        target = root.joinpath(*relative.split("/")).resolve(strict=True)
        target.relative_to(root)
    except (OSError, RuntimeError, ValueError) as exc:
        raise _Refuted("SELECTED_PATH_OUTSIDE_REPOSITORY") from exc
    if not target.is_file():
        raise _Refuted("SELECTED_PATH_NOT_REGULAR_FILE")
    return target


def _bounded_read(path: Path, limit: int, code: str) -> bytes:
    try:
        if path.stat().st_size > limit:
            raise _Unavailable(code)
        raw = path.read_bytes()
    except _Unavailable:
        raise
    except OSError as exc:
        raise _Unavailable(code) from exc
    if len(raw) > limit:
        raise _Unavailable(code)
    return raw


def _git_directories(root: Path) -> tuple[Path, Path]:
    marker = root / ".git"
    try:
        if marker.is_dir():
            git_dir = marker.resolve(strict=True)
        elif marker.is_file():
            text = _bounded_read(marker, 4096, "SOURCE_COORDINATE_UNAVAILABLE").decode("utf-8").strip()
            if not text.startswith("gitdir: "):
                raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
            selected = Path(text[8:])
            git_dir = (selected if selected.is_absolute() else marker.parent / selected).resolve(strict=True)
        else:
            raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
        common_marker = git_dir / "commondir"
        if common_marker.is_file():
            text = _bounded_read(common_marker, 4096, "SOURCE_COORDINATE_UNAVAILABLE").decode("utf-8").strip()
            selected = Path(text)
            common = (selected if selected.is_absolute() else git_dir / selected).resolve(strict=True)
        else:
            common = git_dir
    except (UnicodeError, OSError, RuntimeError, ValueError) as exc:
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE") from exc
    return git_dir, common


def _read_revision(git_dir: Path, common: Path) -> str:
    try:
        head = _bounded_read(git_dir / "HEAD", 4096, "SOURCE_COORDINATE_UNAVAILABLE").decode("ascii").strip()
    except UnicodeError as exc:
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE") from exc
    if _REVISION.fullmatch(head):
        return head
    if not head.startswith("ref: "):
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
    ref = head[5:]
    if (not ref.startswith("refs/") or "\\" in ref
            or any(part in {"", ".", ".."} for part in ref.split("/"))):
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
    for base in (git_dir, common):
        candidate = base.joinpath(*ref.split("/"))
        if candidate.is_file():
            try:
                revision = _bounded_read(candidate, 4096, "SOURCE_COORDINATE_UNAVAILABLE").decode("ascii").strip()
            except UnicodeError as exc:
                raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE") from exc
            if _REVISION.fullmatch(revision):
                return revision
            raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
    packed = common / "packed-refs"
    if packed.is_file():
        try:
            text = _bounded_read(packed, 4 * 1024 * 1024, "SOURCE_COORDINATE_UNAVAILABLE").decode("ascii")
        except UnicodeError as exc:
            raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE") from exc
        matches = [line.split(" ", 1)[0] for line in text.splitlines()
                   if not line.startswith(("#", "^")) and line.endswith(" " + ref)]
        if len(matches) == 1 and _REVISION.fullmatch(matches[0]):
            return matches[0]
    raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")


def _git_coordinate(root: Path) -> tuple[str, str]:
    git_dir, common = _git_directories(root)
    revision = _read_revision(git_dir, common)
    try:
        raw = _bounded_read(common / "config", 1024 * 1024, "SOURCE_COORDINATE_UNAVAILABLE")
        parser = configparser.RawConfigParser()
        parser.read_string(raw.decode("utf-8"))
        repository = parser.get('remote "origin"', "url")
    except (UnicodeError, configparser.Error, configparser.NoOptionError,
            configparser.NoSectionError) as exc:
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE") from exc
    if not repository or len(repository) > 2048:
        raise _Unavailable("SOURCE_COORDINATE_UNAVAILABLE")
    return repository, revision


def _manifest(
    raw: bytes,
    expected_obligations: dict[str, tuple[str, ...] | list[str]],
) -> tuple[dict[str, Any], dict[str, dict[str, str]], list[dict[str, str]]]:
    value = _decode(raw, limit=MAX_MANIFEST_BYTES, code="MANIFEST_INVALID")
    if (set(value) != {"schema_version", "source_coordinate", "files", "obligations"}
            or value["schema_version"] != MANIFEST_SCHEMA):
        raise _Refuted("MANIFEST_CONTRACT_REJECTED")
    coordinate = value["source_coordinate"]
    if (type(coordinate) is not dict or set(coordinate) != {"repository", "revision"}
            or type(coordinate["repository"]) is not str
            or not coordinate["repository"] or len(coordinate["repository"]) > 2048
            or type(coordinate["revision"]) is not str
            or _REVISION.fullmatch(coordinate["revision"]) is None):
        raise _Refuted("SOURCE_COORDINATE_INVALID")
    files = value["files"]
    obligations = value["obligations"]
    if type(files) is not list or not files:
        raise _Refuted("SELECTED_FILES_REQUIRED")
    if len(files) > MAX_FILES:
        raise _Unavailable("SELECTED_FILE_CAPACITY_EXHAUSTED")
    if type(obligations) is not list or not obligations:
        raise _Refuted("OBLIGATIONS_REQUIRED")
    if len(obligations) > MAX_CASE_ROWS:
        raise _Unavailable("OBLIGATION_CAPACITY_EXHAUSTED")
    selected: dict[str, dict[str, str]] = {}
    portable: set[str] = set()
    for row in files:
        if type(row) is not dict or set(row) != {"path", "role", "sha256"}:
            raise _Refuted("SELECTED_FILE_RECORD_INVALID")
        path = _path(row["path"])
        role = row["role"]
        if role not in FILE_ROLES or not _valid_hash(row["sha256"]):
            raise _Refuted("SELECTED_FILE_RECORD_INVALID")
        key = unicodedata.normalize("NFC", path.casefold())
        if path in selected or key in portable:
            raise _Refuted("DUPLICATE_SELECTED_FILE")
        if role == "TEST" and (not path.startswith("tests/") or not path.endswith(".py")):
            raise _Refuted("TEST_PATH_INVALID")
        if role == "TEST" and _recursive_test_path(path):
            raise _Refuted("RECURSIVE_SELF_POLISH_TEST_REFUSED")
        if role in {"SOURCE", "MECHANISM"} and not path.startswith(("src/", "scripts/")):
            raise _Refuted("SOURCE_OR_MECHANISM_PATH_INVALID")
        selected[path] = {"role": role, "sha256": row["sha256"]}
        portable.add(key)
    if [row["path"] for row in files] != sorted(selected):
        raise _Refuted("SELECTED_FILES_NOT_CANONICALLY_ORDERED")
    primary = selected.get(PRIMARY_MECHANISM_PATH)
    if primary is None or primary["role"] != "MECHANISM":
        raise _Refuted("PRIMARY_MECHANISM_NOT_SELECTED")

    seen_cases: set[tuple[str, str]] = set()
    seen_nodes: set[str] = set()
    referenced: set[str] = set()
    normalized: list[dict[str, str]] = []
    for row in obligations:
        fields = {"obligation_id", "case_kind", "node_id", "source_path", "test_path", "mechanism_path"}
        if type(row) is not dict or set(row) != fields:
            raise _Refuted("OBLIGATION_RECORD_INVALID")
        identifier = row["obligation_id"]
        if type(identifier) is not str or _OBLIGATION_ID.fullmatch(identifier) is None:
            raise _Refuted("UNKNOWN_OBLIGATION")
        if identifier not in expected_obligations:
            raise _Refuted("UNKNOWN_OBLIGATION")
        case_kind = row["case_kind"]
        if case_kind not in CASE_KINDS:
            raise _Refuted("OBLIGATION_CASE_KIND_DIFFERS")
        pair = (identifier, case_kind)
        if pair in seen_cases:
            raise _Refuted("DUPLICATE_OBLIGATION_CASE")
        source_path, test_path, mechanism_path = (
            _path(row[name]) for name in ("source_path", "test_path", "mechanism_path")
        )
        for path, role in ((source_path, "SOURCE"), (test_path, "TEST"),
                           (mechanism_path, "MECHANISM")):
            if selected.get(path, {}).get("role") != role:
                raise _Refuted("OBLIGATION_FILE_MAPPING_INVALID")
            referenced.add(path)
        node = _node_id(row["node_id"], test_path)
        if node in seen_nodes:
            raise _Refuted("DUPLICATE_PYTEST_NODE_ID")
        seen_cases.add(pair)
        seen_nodes.add(node)
        normalized.append({name: row[name] for name in sorted(fields)})
    order = {name: index for index, name in enumerate(CASE_KIND_ORDER)}
    observed_order = [(row["obligation_id"], row["case_kind"])
                      for row in obligations]
    if observed_order != sorted(seen_cases, key=lambda item: (item[0], order[item[1]])):
        raise _Refuted("OBLIGATIONS_NOT_CANONICALLY_ORDERED")
    expected_cases = {(identifier, case_kind)
                      for identifier in expected_obligations
                      for case_kind in CASE_KIND_ORDER}
    if seen_cases != expected_cases:
        raise _Refuted("REQUIRED_OBLIGATION_CASE_UNMAPPED")
    if set(selected) != referenced:
        raise _Refuted("SELECTED_FILE_UNMAPPED")
    return value, selected, normalized


def _observe(root: Path, selected: dict[str, dict[str, str]]) -> tuple[dict[str, str], list[str]]:
    observed: dict[str, str] = {}
    mismatches: list[str] = []
    total = 0
    for relative in sorted(selected):
        raw = _bounded_read(
            _resolve_file(root, relative), MAX_SELECTED_FILE_BYTES,
            "SELECTED_FILE_CAPACITY_EXHAUSTED",
        )
        total += len(raw)
        if total > MAX_SELECTED_TOTAL_BYTES:
            raise _Unavailable("SELECTED_FILE_CAPACITY_EXHAUSTED")
        actual = bytes_digest(raw)
        observed[relative] = actual
        if actual != selected[relative]["sha256"]:
            mismatches.append(relative)
    return observed, mismatches


def _outside(root: Path, candidate: Path) -> bool:
    try:
        candidate.resolve(strict=True).relative_to(root)
        return False
    except ValueError:
        return True


def _read_run_file(path: Path, limit: int) -> tuple[bytes | None, bool]:
    try:
        if not path.is_file():
            return None, False
        if path.stat().st_size > limit:
            return None, True
        raw = path.read_bytes()
    except OSError:
        return None, True
    return (raw, False) if len(raw) <= limit else (None, True)


def _run_pytest(root: Path, node_ids: list[str]) -> _RunObservation:
    with tempfile.TemporaryDirectory(prefix="vstd-self-polish-") as temporary:
        temp = Path(temporary).resolve(strict=True)
        if not _outside(root, temp):
            raise _Unavailable("EXTERNAL_TEMP_DIRECTORY_UNAVAILABLE")
        plugin = temp / "_vstd_self_polish_probe.py"
        config = temp / "pytest.ini"
        trace = temp / "trace.json"
        junit = temp / "junit.xml"
        stdout_path = temp / "stdout.bin"
        stderr_path = temp / "stderr.bin"
        plugin.write_text(_PLUGIN_SOURCE, encoding="utf-8", newline="\n")
        config.write_text("[pytest]\n", encoding="utf-8", newline="\n")
        environment = os.environ.copy()
        for name in list(environment):
            if name.upper().startswith(("PYTHON", "PYTEST", "COVERAGE")):
                environment.pop(name)
        environment.update({
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONNOUSERSITE": "1",
            "PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1",
            "PYTHONHASHSEED": "0",
            "PYTHONPATH": os.pathsep.join((str(temp), str(root / "src"))),
            "VSTD_SELF_POLISH_TRACE": str(trace),
        })
        argv = [
            sys.executable, "-m", "pytest", "-q", "--noconftest",
            "-p", "_vstd_self_polish_probe", "-p", "no:cacheprovider",
            "-c", str(config), "-o", "addopts=", "-o", "junit_family=legacy",
            "--rootdir", str(root),
            "--basetemp", str(temp / "pytest-temp"), "--junitxml", str(junit),
            "--", *node_ids,
        ]
        timed_out = False
        returncode: int | None = None
        try:
            with stdout_path.open("wb") as stdout, stderr_path.open("wb") as stderr:
                completed = subprocess.run(
                    argv, cwd=root, env=environment, stdout=stdout, stderr=stderr,
                    timeout=RUN_TIMEOUT_SECONDS, check=False,
                )
            if type(completed.returncode) is int:
                returncode = completed.returncode
        except subprocess.TimeoutExpired:
            timed_out = True
        except OSError as exc:
            raise _Unavailable("PYTEST_EXECUTION_UNAVAILABLE") from exc
        stdout_raw, stdout_overflow = _read_run_file(stdout_path, MAX_OUTPUT_BYTES)
        stderr_raw, stderr_overflow = _read_run_file(stderr_path, MAX_OUTPUT_BYTES)
        junit_raw, junit_overflow = _read_run_file(junit, MAX_JUNIT_BYTES)
        trace_raw, trace_overflow = _read_run_file(trace, MAX_TRACE_BYTES)
        return _RunObservation(
            returncode=returncode,
            timed_out=timed_out,
            overflow=any((stdout_overflow, stderr_overflow, junit_overflow, trace_overflow)),
            stdout_digest=bytes_digest(stdout_raw) if stdout_raw is not None else None,
            stderr_digest=bytes_digest(stderr_raw) if stderr_raw is not None else None,
            junit_raw=junit_raw,
            trace_raw=trace_raw,
        )


def _trace_counts(
    raw: bytes,
    expected_nodes: list[str],
) -> tuple[dict[str, int], list[str], int, dict[str, dict[str, Any]]]:
    value = _decode(raw, limit=MAX_TRACE_BYTES, code="PYTEST_TRACE_INVALID")
    if set(value) != {"schema_version", "collected", "reports", "exitstatus"} \
            or value["schema_version"] != TRACE_SCHEMA:
        raise _Refuted("PYTEST_TRACE_INVALID")
    collected = value["collected"]
    reports = value["reports"]
    if (type(collected) is not list or any(type(node) is not str for node in collected)
            or type(reports) is not list or len(reports) > 3 * MAX_CASE_ROWS
            or type(value["exitstatus"]) is not int):
        raise _Refuted("PYTEST_TRACE_INVALID")
    invalidators: list[str] = []
    if collected != expected_nodes:
        invalidators.append("PYTEST_COLLECTION_MISMATCH")
    phases: dict[str, dict[str, tuple[str, str | None]]] = {}
    for row in reports:
        if (type(row) is not dict or set(row) != {"nodeid", "when", "outcome", "wasxfail"}
                or type(row["nodeid"]) is not str
                or row["when"] not in {"setup", "call", "teardown"}
                or row["outcome"] not in {"passed", "failed", "skipped"}
                or (row["wasxfail"] is not None and type(row["wasxfail"]) is not str)):
            raise _Refuted("PYTEST_TRACE_INVALID")
        node_phases = phases.setdefault(row["nodeid"], {})
        if row["when"] in node_phases:
            raise _Refuted("PYTEST_TRACE_INVALID")
        node_phases[row["when"]] = (row["outcome"], row["wasxfail"])
    expected_set = set(expected_nodes)
    if set(phases) - expected_set:
        invalidators.append("PYTEST_UNSELECTED_RESULT")
    counts = {"expected": len(expected_nodes), "collected": len(collected),
              "passed": 0, "failed": 0, "skipped": 0, "xfailed": 0, "xpassed": 0}
    node_results: dict[str, dict[str, Any]] = {}
    for node in expected_nodes:
        rows = phases.get(node, {})
        complete = set(rows) == {"setup", "call", "teardown"}
        if not complete:
            invalidators.append("PYTEST_OUTCOME_INCOMPLETE")
        ordered_phases = [phase for phase in ("setup", "call", "teardown") if phase in rows]
        outcomes = [rows[phase][0] for phase in ordered_phases]
        xfail_outcomes = [item[0] for item in rows.values() if item[1] is not None]
        if any(outcome == "failed" for outcome in outcomes):
            counts["failed"] += 1
        if any(outcome == "skipped" for outcome in outcomes):
            counts["skipped"] += 1
        if "skipped" in xfail_outcomes:
            counts["xfailed"] += 1
        if "passed" in xfail_outcomes:
            counts["xpassed"] += 1
        if complete and outcomes == ["passed", "passed", "passed"] and not xfail_outcomes:
            counts["passed"] += 1
            status = "PASS"
        elif outcomes:
            status = "FAIL"
        else:
            status = "UNKNOWN"
        node_results[node] = {
            "status": status,
            "reports": [
                {"when": phase, "outcome": rows[phase][0], "wasxfail": rows[phase][1]}
                for phase in ordered_phases
            ],
        }
    if counts["skipped"]:
        invalidators.append("PYTEST_SKIP_REFUSED")
    if counts["xfailed"] or counts["xpassed"]:
        invalidators.append("PYTEST_XFAIL_REFUSED")
    if counts["passed"] != len(expected_nodes):
        invalidators.append("PYTEST_NOT_ALL_SELECTED_NODES_PASSED")
    return counts, list(dict.fromkeys(invalidators)), value["exitstatus"], node_results


def _check_junit(raw: bytes, expected: int) -> list[str]:
    if b"<!DOCTYPE" in raw or b"<!ENTITY" in raw:
        raise _Refuted("JUNIT_XML_INVALID")
    try:
        root = ElementTree.fromstring(raw)
    except ElementTree.ParseError as exc:
        raise _Refuted("JUNIT_XML_INVALID") from exc
    cases = list(root.iter("testcase"))
    invalidators: list[str] = []
    if len(cases) != expected:
        invalidators.append("JUNIT_COLLECTION_MISMATCH")
    if any(case.find("failure") is not None or case.find("error") is not None for case in cases):
        invalidators.append("JUNIT_FAILURE_OR_ERROR")
    if any(case.find("skipped") is not None for case in cases):
        invalidators.append("JUNIT_SKIP_OR_XFAIL_REFUSED")
    return invalidators


def _finish(receipt: dict[str, Any]) -> dict[str, Any]:
    receipt["invalidators"] = list(dict.fromkeys(receipt["invalidators"]))[:32]
    body = canonical_bytes(receipt)
    if len(body) > MAX_RECEIPT_BYTES:
        receipt = {
            "schema_version": RECEIPT_SCHEMA,
            "status": "UNKNOWN",
            "tier": 1,
            "polished": False,
            "release_authority": "NONE",
            "whole_tier_conformance": "NOT_ESTABLISHED",
            "provider_states": "OUT_OF_SCOPE",
            "manifest_digest": receipt.get("manifest_digest"),
            "stable_replay_set_digest": None,
            "evidence_digest": None,
            "run_artifacts": {
                "pytest_trace_digest": None,
                "junit_xml_digest": None,
                "stdout_digest": None,
                "stderr_digest": None,
            },
            "source_coordinate": None,
            "memberships": [],
            "counts": {"expected": 0, "collected": 0, "passed": 0,
                       "failed": 0, "skipped": 0, "xfailed": 0, "xpassed": 0},
            "invalidators": ["RECEIPT_CAPACITY_EXHAUSTED"],
            "claim_boundary": _BOUNDARY,
        }
    receipt["receipt_digest"] = bytes_digest(canonical_bytes(receipt))
    return receipt


def replay_self_polish_evidence(
    manifest_bytes: bytes,
    repo_root: str | Path,
    *,
    expected_manifest_digest: str | None,
    expected_mechanism_digest: str | None,
    expected_obligations: dict[str, tuple[str, ...] | list[str]],
) -> dict[str, Any]:
    """Freshly replay an independently selected finite Tier 1 test mapping.

    ``expected_obligations`` is the separately selected denominator. Each key
    must map to ``("POSITIVE", "NEGATIVE", "UNKNOWN")`` and the manifest must
    supply exactly one unique node for each pair. The denominator is not
    evidence; its digest is reported. The current 45-membership Tier 1 denominator is
    intentionally not embedded here.
    """

    manifest_digest = bytes_digest(manifest_bytes) if type(manifest_bytes) is bytes else None
    receipt: dict[str, Any] = {
        "schema_version": RECEIPT_SCHEMA,
        "status": "UNKNOWN",
        "tier": 1,
        "polished": False,
        "release_authority": "NONE",
        "whole_tier_conformance": "NOT_ESTABLISHED",
        "provider_states": "OUT_OF_SCOPE",
        "manifest_digest": manifest_digest,
        "expected_manifest_digest": expected_manifest_digest if _valid_hash(expected_manifest_digest) else None,
        "mechanism_digest": None,
        "expected_mechanism_digest": expected_mechanism_digest if _valid_hash(expected_mechanism_digest) else None,
        "obligation_mapping_digest": None,
        "stable_replay_set_digest": None,
        "evidence_digest": None,
        "run_artifacts": {
            "pytest_trace_digest": None,
            "junit_xml_digest": None,
            "stdout_digest": None,
            "stderr_digest": None,
        },
        "source_coordinate": None,
        "memberships": [],
        "counts": {"expected": 0, "collected": 0, "passed": 0,
                   "failed": 0, "skipped": 0, "xfailed": 0, "xpassed": 0},
        "invalidators": [],
        "claim_boundary": _BOUNDARY,
    }

    def invalidate(code: str) -> None:
        receipt["invalidators"].append(code)

    try:
        if (not _valid_hash(expected_manifest_digest)
                or not _valid_hash(expected_mechanism_digest)):
            raise _Refuted("INDEPENDENT_DIGEST_PIN_REQUIRED")
        if manifest_digest != expected_manifest_digest:
            raise _Refuted("MANIFEST_DIGEST_MISMATCH")
        if type(expected_obligations) is not dict or not expected_obligations \
                or len(expected_obligations) > MAX_MEMBERSHIPS:
            raise _Refuted("OBLIGATION_DENOMINATOR_INVALID")
        if any(
            type(key) is not str or _OBLIGATION_ID.fullmatch(key) is None
            or type(value) not in (tuple, list)
            or tuple(value) != CASE_KIND_ORDER
            for key, value in expected_obligations.items()
        ):
            raise _Refuted("OBLIGATION_DENOMINATOR_INVALID")
        mapping = [{"obligation_id": key, "required_case_kinds": list(CASE_KIND_ORDER)}
                   for key in sorted(expected_obligations)]
        receipt["obligation_mapping_digest"] = bytes_digest(canonical_bytes(mapping))

        root = Path(repo_root).resolve(strict=True)
        if not root.is_dir():
            raise _Unavailable("REPOSITORY_ROOT_UNAVAILABLE")
        runtime_mechanism_before = mechanism_digest()
        receipt["mechanism_digest"] = runtime_mechanism_before
        if runtime_mechanism_before != expected_mechanism_digest:
            raise _Refuted("MECHANISM_DIGEST_MISMATCH")

        manifest, selected, obligations = _manifest(manifest_bytes, expected_obligations)
        cases_by_obligation: dict[str, list[dict[str, Any]]] = {
            identifier: [] for identifier in sorted(expected_obligations)
        }
        for row in obligations:
            cases_by_obligation[row["obligation_id"]].append({
                "case_kind": row["case_kind"],
                "node_id": row["node_id"],
                "source": {"path": row["source_path"],
                           "sha256": selected[row["source_path"]]["sha256"]},
                "test": {"path": row["test_path"],
                         "sha256": selected[row["test_path"]]["sha256"]},
                "mechanism": {"path": row["mechanism_path"],
                              "sha256": selected[row["mechanism_path"]]["sha256"]},
                "status": "UNKNOWN",
            })
        receipt["memberships"] = [
            {"obligation_id": identifier, "cases": cases_by_obligation[identifier],
             "status": "UNKNOWN", "stable_replay_digest": None}
            for identifier in sorted(cases_by_obligation)
        ]
        expected_coordinate = manifest["source_coordinate"]
        repository_before, revision_before = _git_coordinate(root)
        if (repository_before != expected_coordinate["repository"]
                or revision_before != expected_coordinate["revision"]):
            raise _Refuted("SOURCE_COORDINATE_MISMATCH")
        observed_before, mismatches = _observe(root, selected)
        receipt["source_coordinate"] = {
            "repository": repository_before,
            "revision": revision_before,
            "selected_files_digest": bytes_digest(canonical_bytes(observed_before)),
            "scope": "SELECTED_FILES_ONLY",
        }
        if mismatches:
            raise _Refuted("SELECTED_FILE_DIGEST_MISMATCH")
        if observed_before[PRIMARY_MECHANISM_PATH] != runtime_mechanism_before:
            raise _Refuted("PRIMARY_MECHANISM_COPY_DIFFERS")

        node_ids = [row["node_id"] for row in obligations]
        observation = _run_pytest(root, node_ids)
        receipt["run_artifacts"] = {
            "pytest_trace_digest": (
                bytes_digest(observation.trace_raw)
                if observation.trace_raw is not None else None
            ),
            "junit_xml_digest": (
                bytes_digest(observation.junit_raw)
                if observation.junit_raw is not None else None
            ),
            "stdout_digest": observation.stdout_digest,
            "stderr_digest": observation.stderr_digest,
        }

        repository_after, revision_after = _git_coordinate(root)
        observed_after, after_mismatches = _observe(root, selected)
        runtime_mechanism_after = mechanism_digest()
        if ((repository_after, revision_after) != (repository_before, revision_before)
                or observed_after != observed_before
                or after_mismatches
                or runtime_mechanism_after != runtime_mechanism_before):
            raise _Refuted("SELECTED_SOURCE_STALE_AFTER_REPLAY")
        if observation.timed_out:
            raise _Unavailable("PYTEST_TIME_BOUND_EXHAUSTED")
        if observation.overflow:
            raise _Unavailable("PYTEST_OUTPUT_CAPACITY_EXHAUSTED")
        if observation.trace_raw is None or observation.junit_raw is None:
            raise _Refuted("PYTEST_EVIDENCE_MISSING")

        counts, trace_invalidators, trace_exitstatus, node_results = _trace_counts(
            observation.trace_raw, node_ids,
        )
        receipt["counts"] = counts
        for code in trace_invalidators:
            invalidate(code)
        for code in _check_junit(observation.junit_raw, len(node_ids)):
            invalidate(code)
        if observation.returncode is None:
            invalidate("PYTEST_RETURN_CODE_MISSING")
        elif observation.returncode != 0:
            invalidate("PYTEST_NONZERO_EXIT")
        if observation.returncode != trace_exitstatus:
            invalidate("PYTEST_EXIT_STATUS_MISMATCH")
        run_accepted = not receipt["invalidators"]
        for membership in receipt["memberships"]:
            case_results = []
            raw_statuses = []
            for case in membership["cases"]:
                result = node_results[case["node_id"]]
                case["status"] = result["status"]
                raw_statuses.append(result["status"])
                case_results.append({
                    "case_kind": case["case_kind"],
                    "node_id": case["node_id"],
                    "derived_status": result["status"],
                    "reports": result["reports"],
                })
            aggregate_status = (
                "FAIL" if "FAIL" in raw_statuses else
                "UNKNOWN" if "UNKNOWN" in raw_statuses else
                "PASS" if raw_statuses == ["PASS", "PASS", "PASS"] else
                "FAIL"
            )
            membership["status"] = (
                aggregate_status if run_accepted or aggregate_status == "UNKNOWN"
                else "FAIL"
            )
            membership["stable_replay_digest"] = bytes_digest(canonical_bytes({
                "schema_version": STABLE_MEMBERSHIP_SCHEMA,
                "manifest_digest": manifest_digest,
                "obligation_mapping_digest": receipt["obligation_mapping_digest"],
                "source_coordinate": receipt["source_coordinate"],
                "membership": {
                    "obligation_id": membership["obligation_id"],
                    "cases": [
                        {key: case[key] for key in (
                            "case_kind", "node_id", "source", "test", "mechanism",
                        )}
                        for case in membership["cases"]
                    ],
                },
                "derived_status": membership["status"],
                "case_results": case_results,
                "returncode": observation.returncode,
                "counts": counts,
            }))
        stable_replay_set = {
            "schema_version": "verifier-self-polish-stable-replay-set-1",
            "manifest_digest": manifest_digest,
            "obligation_mapping_digest": receipt["obligation_mapping_digest"],
            "source_coordinate": receipt["source_coordinate"],
            "observed_files": observed_after,
            "returncode": observation.returncode,
            "counts": counts,
            "stable_membership_replay_digests": {
                row["obligation_id"]: row["stable_replay_digest"]
                for row in receipt["memberships"]
            },
        }
        receipt["stable_replay_set_digest"] = bytes_digest(
            canonical_bytes(stable_replay_set),
        )
        receipt["evidence_digest"] = bytes_digest(canonical_bytes({
            "schema_version": "verifier-self-polish-run-evidence-1",
            "stable_replay_set": stable_replay_set,
            "run_artifacts": receipt["run_artifacts"],
        }))
        receipt["status"] = "FAIL" if receipt["invalidators"] else "PASS"
    except _Refuted as exc:
        invalidate(str(exc))
        receipt["status"] = "FAIL"
    except _Unavailable as exc:
        invalidate(str(exc))
        receipt["status"] = "UNKNOWN"
    except (OSError, RuntimeError, MemoryError, RecursionError, OverflowError,
            UnicodeError, ValueError, TypeError, KeyError, AttributeError):
        invalidate("SELF_POLISH_EVIDENCE_MECHANISM_UNAVAILABLE")
        receipt["status"] = "UNKNOWN"
    return _finish(receipt)


