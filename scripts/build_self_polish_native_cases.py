def _receipt_replay_case(
        seed: dict[str, Any],
        rebinder: source_rebinding.SourceCaseRebinder,
        ) -> dict[str, Any]:
    retained = json.loads(base64.b64decode(
        seed["evidence_base64"], validate=True
    ))
    old_receipt = json.loads(base64.b64decode(
        retained["receipt_base64"], validate=True
    ))
    receipt = _receipt_from_semantic_seed(old_receipt)
    retained_object = retained["receipt_object"]
    payload = dict(retained_object["payload"])
    payload["receipt_sha256"] = (
        "sha256:" + hashlib.sha256(receipt).hexdigest()
    )
    item = NamespaceObject.create(
        retained_object["object_id"], retained_object["kind"], payload,
        retained_object["operands"],
    )
    evidence_value = {
        "schema_version": receipt_validation_replay.EVIDENCE_VERSION,
        "receipt_object": item.to_dict(),
        "receipt_base64": base64.b64encode(receipt).decode("ascii"),
    }
    evidence = canonical_bytes(evidence_value)
    policy = rebinder.refresh_policy(seed["policy"])
    request = receipt_validation_replay.receipt_validation_replay_request(
        subject_id=item.object_id, object_digest=item.digest,
        expected_satisfiable=seed["request"]["expected_satisfiable"],
        evidence_ref=("sha256:" + hashlib.sha256(evidence).hexdigest()),
        policy=policy, limits=seed["request"]["limits"],
    )
    case = dict(seed)
    case.update({
        "policy": policy,
        "request": request,
        "evidence_base64": base64.b64encode(evidence).decode("ascii"),
    })
    return case


def _negative_refusal_code(result: dict[str, Any]) -> str:
    """Return the checker-emitted refusal code for a NEGATIVE result.

    The code is the negative contract's own reason, not the bare FAIL status.
    """
    evaluation = result.get("evaluation")
    code = evaluation.get("details") if type(evaluation) is dict else None
    if type(code) is not str or not code:
        raise RuntimeError("negative case FAIL carries no intended refusal code")
    return code


def _validate_case(
        identifier: str, case: dict[str, Any], positive: str = "PASS",
        ) -> dict[str, str]:
    """Replay the triad under current source and return the observed outcomes."""

    _, recheck_name = case["checking_mechanism"].rsplit(".", 1)
    module = current_object_routes.registered_mechanism_module(
        case["checking_mechanism"]
    )
    builder = getattr(module, recheck_name.replace("recheck_", "build_", 1))
    rechecker = getattr(module, recheck_name)
    request, policy = case["request"], case["policy"]
    evidence = base64.b64decode(case["evidence_base64"], validate=True)
    negative_request, negative_evidence = self_polish_native_replay._negative_case(
        module, identifier, request
    )
    selected = (
        ("POSITIVE", positive, request, evidence),
        ("NEGATIVE", "FAIL", negative_request, negative_evidence),
        ("UNKNOWN", "UNKNOWN", request, None),
    )
    observed: dict[str, str] = {}
    for case_kind, expected, selected_request, selected_evidence in selected:
        certificate = builder(
            selected_request, selected_evidence, policy=policy
        )
        result = rechecker(
            certificate, expected_request=selected_request, policy=policy
        )
        if result.get("status") != expected:
            raise RuntimeError(
                "base native case triad status differs: "
                f"{identifier} {case_kind} expected {expected} observed "
                f"{result.get('status')}"
            )
        observed[case_kind] = result["status"]
        if case_kind == "NEGATIVE":
            NEGATIVE_REFUSAL_CODES[identifier] = _negative_refusal_code(result)
    return observed


def _triad_case_bindings(
        identifier: str, case: dict[str, Any], triad: dict[str, str],
        ) -> dict[str, dict[str, Any]]:
    """Bind each replay variant without treating replay as source acceptance."""

    module = current_object_routes.registered_mechanism_module(
        case["checking_mechanism"]
    )
    negative_request, negative_evidence = self_polish_native_replay._negative_case(
        module, identifier, case["request"]
    )
    evidence = base64.b64decode(case["evidence_base64"], validate=True)
    selected = {
        "POSITIVE": (case["request"], evidence),
        "NEGATIVE": (negative_request, negative_evidence),
        "UNKNOWN": (case["request"], None),
    }
    policy_digest = core_obligation_union.value_digest(case["policy"])
    bindings: dict[str, dict[str, Any]] = {}
    for case_kind, (request, selected_evidence) in selected.items():
        evidence_digest = (
            core_obligation_union.bytes_digest(selected_evidence)
            if type(selected_evidence) is bytes
            else core_obligation_union.value_digest({"evidence": None})
        )
        intended = (
            [NEGATIVE_REFUSAL_CODES[identifier]]
            if case_kind == "NEGATIVE" else []
        )
        binding = {
            "case_kind": case_kind,
            "checking_mechanism": case["checking_mechanism"],
            "policy_digest": policy_digest,
            "request_digest": core_obligation_union.value_digest(request),
            "evidence_present": type(selected_evidence) is bytes,
            "evidence_digest": evidence_digest,
            "expected_native_status": triad[case_kind],
            "intended_refusal_codes": intended,
        }
        binding["case_digest"] = core_obligation_union.value_digest({
            key: binding[key] for key in (
                "case_kind", "checking_mechanism", "evidence_digest",
                "expected_native_status", "intended_refusal_codes",
                "policy_digest", "request_digest",
            )
        })
        bindings[case_kind] = binding
    return bindings


def _rebound_cases() -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, str]]]:
    """Rebuild every non-patch case and return the triad outcomes observed."""

    seed = _seed_cases()
    rebinder = source_rebinding.SourceCaseRebinder(seed)
    payload: dict[str, dict[str, Any]] = {}
    triads: dict[str, dict[str, str]] = {}
    for identifier in sorted(seed):
        if identifier in PATCH_OWNED_IDENTIFIERS:
            payload[identifier] = seed[identifier]
            continue
        if identifier == "OBJECT:OBJECT-1.1":
            case = _object_facets_case(seed[identifier], rebinder)
        elif identifier == "RECEIPT:RECEIPT-2.1":
            case = _receipt_replay_case(seed[identifier], rebinder)
        else:
            case = rebinder.refresh_case(seed[identifier])
        triads[identifier] = _validate_case(identifier, case)
        payload[identifier] = case
    if len(payload) != ENTRY_COUNT or set(payload) != set(seed):
        raise RuntimeError("base native case denominator differs")
    return payload, triads


def build_cases() -> dict[str, dict[str, Any]]:
    return _rebound_cases()[0]


def build_payload() -> tuple[bytes, bytes]:
    raw, encoded, _ = build_payload_with_triads()
    return raw, encoded


def build_payload_with_triads() -> tuple[bytes, bytes, dict[str, dict[str, str]]]:
    payload, triads = _rebound_cases()
    raw = canonical_bytes(payload)
    encoded = base64.b85encode(zlib.compress(raw, 9))
    if (
        len(raw) > MAX_DECOMPRESSED_PAYLOAD_BYTES
        or len(encoded) > MAX_ENCODED_PAYLOAD_BYTES
    ):
        raise RuntimeError("base native case payload exceeds installed bounds")
    return raw, encoded, triads


def _closure_of(module: Any) -> list[dict[str, str]]:
    """Record the exact source files a mechanism digest reads, with their bytes."""

    reads: list[str] = []
    original = Path.read_bytes

    def recording(self: Path) -> bytes:
        reads.append(str(self.resolve()))
        return original(self)

    Path.read_bytes = recording  # type: ignore[assignment]
    try:
        module.mechanism_digest()
    finally:
        Path.read_bytes = original  # type: ignore[assignment]
    closure = []
    for item in sorted(set(reads)):
        path = Path(item)
        relative = path.relative_to(ROOT).as_posix()
        closure.append({
            "path": relative,
            "sha256": core_obligation_union.bytes_digest(path.read_bytes()),
        })
    return closure


def _validated_reviewed_prior_pins(
        base_seed: dict[str, dict[str, Any]],
        ) -> dict[str, str]:
    """Return the immutable prior pins after checking the complete baseline.

    The generated module is deliberately not consulted. The outer digest binds
    the source revision, historical module and payload bytes, reproduced
    closures, identities, and pins as one review decision.
    """

    baseline = REVIEWED_PRIOR_BASELINE
    rows = baseline.get("rows") if type(baseline) is dict else None
    if (
        core_obligation_union.value_digest(baseline)
        != REVIEWED_PRIOR_BASELINE_DIGEST
        or type(rows) is not tuple
        or len(rows) != ENTRY_COUNT
    ):
        raise RuntimeError("reviewed prior baseline differs")
    pins: dict[str, str] = {}
    for row in rows:
        if (
            type(row) is not tuple or len(row) != 2
            or type(row[0]) is not str or not row[0]
            or type(row[1]) is not str or len(row[1]) != 71
            or not row[1].startswith("sha256:")
            or row[0] in pins
        ):
            raise RuntimeError("reviewed prior baseline differs")
        pins[row[0]] = row[1]
    if set(pins) != set(base_seed):
        raise RuntimeError("reviewed prior baseline differs")
    return pins


def _disposition(identifier: str) -> tuple[str, str, str]:
    if identifier == "RECEIPT:RECEIPT-2.1":
        return (
            "ACCEPT_REPIN",
            "the exact current-source receipt replay closure, request, policy, "
            "evidence, intended refusal, and three native outcome lanes were "
            "reviewed together; the embedded historical fixture provenance is "
            "outside this structural replay proposition and remains "
            "non-authoritative",
            "Preserve the fixture provenance boundary and rerun all three native lanes after any source change.",
        )
    if identifier in CURRENT_SOURCE_ACCEPTED_REPIN_IDENTIFIERS:
        return (
            "ACCEPT_REPIN",
            "the exact current-source mechanism closure, request, policy, "
            "evidence, intended refusal, and three native outcome lanes were "
            "reviewed together; the current binding is accepted without claiming "
            "that the unresolved historical pin was reproduced",
            "Preserve the reviewed closure and rerun all three native lanes after any source change.",
        )
    if identifier in ACCEPTED_REPIN_IDENTIFIERS:
        if identifier.startswith("SIM:"):
            reason = (
                "the exact prior pin and its bc19a6c0 closure were reproduced; "
                "the bounded current triad was replayed and the reviewed semantic "
                "delta is accepted for this coordinate"
            )
        else:
            reason = (
                "the exact prior SPACE pin and committed closure were reproduced; "
                "the current change is the reviewed normative namespace-document "
                "delta and the bounded current triad was replayed"
            )
        return (
            "ACCEPT_REPIN", reason,
            "Preserve both closure coordinates and rerun the triad after any source change.",
        )
    if identifier == "SIM:SIM-2.4":
        return (
            "UNKNOWN_FIXTURE_ONLY_RESOURCE",
            "SIM-2.4 resource specimen is UNKNOWN by design; its collector key is "
            "the public fixture seed labeled "
            f"{sim_patch.FIXTURE_AUTHORITY}, which cannot establish authority",
            "Supply source-bound collector identity, honesty, and use evidence that is not the public fixture seed.",
        )
    return (
        "UNKNOWN_BASELINE_UNRESOLVED",
        "stored policy digest is not reproduced at any reviewed revision; "
        "current triad replays but semantic continuity with the stored pin is "
        "not established",
        "Locate a revision that reproduces the prior pin, reconstruct its exact closure, and review the delta.",
    )


def build_source_review(
        cases: dict[str, dict[str, Any]],
        triads: dict[str, dict[str, str]],
        base_seed: dict[str, dict[str, Any]],
        ) -> dict[str, Any]:
    """Derive one row per entry from the final installed cases and closures."""

    stored_carry = _validated_reviewed_prior_pins(base_seed)
    reproduced = REVIEWED_PRIOR_BASELINE["reproduced_closures"]
    closures: dict[str, list[dict[str, str]]] = {}
    rows = []
    for identifier in sorted(cases):
        case = cases[identifier]
        mechanism = case["checking_mechanism"]
        module_name = mechanism.rsplit(".", 1)[0]
        module = current_object_routes.registered_mechanism_module(mechanism)
        if module_name not in closures:
            closures[module_name] = _closure_of(module)
        closure = closures[module_name]
        closure_paths = [item["path"] for item in closure]
        baseline = reproduced.get(identifier)
        if identifier == "SPACE:SPACE-2.1":
            deltas = sorted(p for p in closure_paths if p in DELTAS_VS_HEAD)
        else:
            deltas = sorted(p for p in closure_paths if p in DELTAS_VS_BC19A6C0)
        disposition, reason, next_action = _disposition(identifier)
        current_pin = module.mechanism_digest()
        stored = stored_carry[identifier]
        triad = triads.get(identifier) or {
            "POSITIVE": SIM_POSITIVE[identifier],
            "NEGATIVE": "FAIL",
            "UNKNOWN": "UNKNOWN",
        }
        evidence = base64.b64decode(case["evidence_base64"], validate=True)
        policy_digest = core_obligation_union.value_digest(case["policy"])
        request_digest = core_obligation_union.value_digest(case["request"])
        evidence_digest = core_obligation_union.bytes_digest(evidence)
        case_digest = core_obligation_union.value_digest({
            "checking_mechanism": mechanism,
            "evidence_digest": evidence_digest,
            "policy_digest": policy_digest,
            "request_digest": request_digest,
        })
        rows.append({
            "identifier": identifier,
            "family": identifier.split(":", 1)[0],
            "coordinate": identifier.split(":", 1)[1],
            "checking_mechanism": mechanism,
            "coordinate_digest": core_obligation_union.value_digest({
                "identifier": identifier,
                "checking_mechanism": mechanism,
                "request": case["request"],
            }),
            "policy_digest": policy_digest,
            "request_digest": request_digest,
            "evidence_digest": evidence_digest,
            "case_digest": case_digest,
            "intended_negative_refusal_codes": [
                NEGATIVE_REFUSAL_CODES[identifier]
            ],
            "stored_policy_mechanism_digest": stored,
            "current_policy_mechanism_digest": current_pin,
            "stored_pin_matches_current": stored == current_pin,
            "reviewed_closure_digest": core_obligation_union.value_digest(closure),
            "reviewed_closure_file_count": len(closure),
            "prior_pin_source_revision": REVIEWED_PRIOR_BASELINE[
                "source_revision"
            ],
            "baseline_revision": (
                baseline["revision"] if baseline is not None else None
            ),
            "baseline_closure_digest": (
                baseline["closure_digest"] if baseline is not None else None
            ),
            "baseline_status": (
                "REPRODUCED_REVIEWED_ACCEPTED"
                if disposition == "ACCEPT_REPIN" and baseline is not None
                else "CURRENT_SOURCE_REVIEWED_REPIN"
                if disposition == "ACCEPT_REPIN"
                else "PRIOR_PIN_CAPTURED_BASELINE_UNRESOLVED"
            ),
            "baseline_closure_deltas": deltas,
            "verified_triad": triad,
            "triad_cases": _triad_case_bindings(identifier, case, triad),
            "disposition": disposition,
            "reason": reason,
            "next_action": next_action,
        })
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["disposition"]] = counts.get(row["disposition"], 0) + 1
    return {
        "schema_version": SOURCE_REVIEW_SCHEMA,
        "reviewed_prior_baseline_digest": REVIEWED_PRIOR_BASELINE_DIGEST,
        "reviewed_prior_source_revision": REVIEWED_PRIOR_BASELINE[
            "source_revision"
        ],
        "entry_count": len(rows),
        "status": "UNKNOWN" if any(
            row["disposition"].startswith("UNKNOWN_") for row in rows
        ) else "PASS",
        "disposition_counts": dict(sorted(counts.items())),
        "rows": rows,
    }


