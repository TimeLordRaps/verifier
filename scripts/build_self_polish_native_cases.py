def _chunks(encoded: bytes) -> str:
    return "\n".join(
        "    b'" + encoded[offset:offset + 88].decode("ascii") + "'"
        for offset in range(0, len(encoded), 88)
    )


def render_native_cases_module(
        encoded: bytes, raw: bytes, ledger_encoded: bytes, ledger_raw: bytes,
        entry_count: int,
        ) -> bytes:
    """Render the complete native case module from the builder template."""

    codes = "{" + ", ".join(
        f"{identifier!r}: {code!r}"
        for identifier, code in sorted(NEGATIVE_REFUSAL_CODES.items())
    ) + "}"
    accepted = "(" + ", ".join(
        repr(identifier) for identifier in sorted(ACCEPTED_REPIN_IDENTIFIERS)
    ) + ",)"
    source = (
        _CASES_TEMPLATE
        .replace("@@ENTRY_COUNT@@", str(entry_count))
        .replace("@@CASE_DIGEST@@", repr(core_obligation_union.bytes_digest(raw)))
        .replace("@@LEDGER_SCHEMA@@", SOURCE_REVIEW_SCHEMA)
        .replace("@@LEDGER_DIGEST@@", repr(core_obligation_union.bytes_digest(ledger_raw)))
        .replace("@@BASELINE_DIGEST@@", repr(REVIEWED_PRIOR_BASELINE_DIGEST))
        .replace("@@ACCEPTED_IDENTIFIERS@@", accepted)
        .replace("@@ACCEPTED_COUNT@@", str(len(ACCEPTED_REPIN_IDENTIFIERS)))
        .replace("@@UNKNOWN_COUNT@@", str(entry_count - len(ACCEPTED_REPIN_IDENTIFIERS)))
        .replace("@@NEGATIVE_CODES@@", codes)
        .replace("@@MAX_ENCODED@@", str(MAX_ENCODED_PAYLOAD_BYTES))
        .replace("@@MAX_DECOMPRESSED@@", str(MAX_DECOMPRESSED_PAYLOAD_BYTES))
        .replace("@@MAX_LEDGER@@", str(MAX_LEDGER_BYTES))
        .replace("@@PAYLOAD_BLOCK@@", _chunks(encoded))
        .replace("@@LEDGER_BLOCK@@", _chunks(ledger_encoded))
    )
    return source.encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    sources = build_installed_sources()
