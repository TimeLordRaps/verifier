def build_installed_sources() -> dict[str, bytes]:
    """Derive base, overlay, ledger and native module bytes in one process."""

    base_raw, base_encoded, triads = build_payload_with_triads()
    seed = json.loads(base_raw)
    patch_module, patch = sim_patch.render_patch_module(base_raw)
    for identifier in sorted(PATCH_OWNED_IDENTIFIERS):
        triads[identifier] = _validate_case(
            identifier, patch[identifier], SIM_POSITIVE[identifier]
        )
    cases = _installed_cases_view(base_raw, patch)
    ledger = build_source_review(cases, triads, seed)
    ledger_raw = _canonical(ledger)
    if len(ledger_raw) > MAX_LEDGER_BYTES:
        raise RuntimeError("source review ledger exceeds installed bounds")
    ledger_encoded = base64.b85encode(zlib.compress(ledger_raw, 9))
    return {
        "native_cases": render_native_cases_module(
            base_encoded, base_raw, ledger_encoded, ledger_raw, len(seed),
        ),
        "sim_patch": patch_module,
    }


